function readCleanupJournal(targetDir) {
	const journalPath = resolveRepoPath(targetDir, CLEANUP_JOURNAL_REL, "cleanup journal path");
	const parentPath = path.dirname(journalPath);
	let before;
	try {
		before = fs.lstatSync(journalPath);
	} catch (err) {
		if (err.code === "ENOENT") return null;
		throw err;
	}
	let parentDescriptor = null;
	let journalDescriptor = null;
	let text;
	try {
		const parentBefore = fs.lstatSync(parentPath);
		if (parentBefore.isSymbolicLink() || !parentBefore.isDirectory()) {
			throw new Error("cleanup journal parent must be a non-symlinked directory");
		}
		parentDescriptor = fs.openSync(
			parentPath,
			fs.constants.O_RDONLY | fs.constants.O_DIRECTORY | fs.constants.O_NOFOLLOW,
		);
		const parentOpened = fs.fstatSync(parentDescriptor);
		if (!sameFileIdentity(parentBefore, parentOpened)) {
			throw new Error("cleanup journal parent changed before it could be opened");
		}
		const descriptorPath =
			process.platform === "linux"
				? path.join(`/proc/self/fd/${parentDescriptor}`, path.basename(journalPath))
				: journalPath;
		journalDescriptor = fs.openSync(descriptorPath, fs.constants.O_RDONLY | fs.constants.O_NOFOLLOW);
		const opened = fs.fstatSync(journalDescriptor);
		const currentUid = typeof process.getuid === "function" ? process.getuid() : null;
		const safeShape = (stat) =>
			stat.isFile() &&
			!stat.isSymbolicLink() &&
			(stat.mode & 0o777) === 0o600 &&
			stat.nlink === 1 &&
			(currentUid === null || stat.uid === currentUid);
		if (!safeShape(before) || !safeShape(opened) || !sameFileIdentity(before, opened)) {
			throw new Error(
				"cleanup journal must be one unchanged regular file owned by the current user, single-linked, and exactly mode 0600",
			);
		}
		text = fs.readFileSync(journalDescriptor, "utf8");
		const openedAfter = fs.fstatSync(journalDescriptor);
		const after = fs.lstatSync(journalPath);
		const parentAfter = fs.lstatSync(parentPath);
		if (
			!safeShape(openedAfter) ||
			!safeShape(after) ||
			!sameFileIdentity(opened, openedAfter) ||
			!sameFileIdentity(opened, after) ||
			!sameFileIdentity(parentOpened, parentAfter)
		) {
			throw new Error("cleanup journal or its parent changed while it was read");
		}
	} finally {
		if (journalDescriptor !== null) {
			try {
				fs.closeSync(journalDescriptor);
			} catch {}
		}
		if (parentDescriptor !== null) {
			try {
				fs.closeSync(parentDescriptor);
			} catch {}
		}
	}
	const parsed = JSON.parse(text);
	if (
		typeof parsed !== "object" ||
		parsed === null ||
		parsed.version !== 1 ||
		!Array.isArray(parsed.entries) ||
		parsed.entries.length === 0
	) {
		throw new Error("cleanup journal has an invalid schema");
	}
	for (const entry of parsed.entries) {
		if (
			typeof entry !== "object" ||
			entry === null ||
			!["planned", "quarantined", "unresolved"].includes(entry.phase) ||
			typeof entry.source !== "string" ||
			typeof entry.quarantine !== "string" ||
			typeof entry.parentDev !== "string" ||
			typeof entry.parentIno !== "string" ||
			typeof entry.fileDev !== "string" ||
			typeof entry.fileIno !== "string" ||
			typeof entry.keepSource !== "boolean" ||
			typeof entry.reason !== "string" ||
			entry.source === entry.quarantine ||
			!MANIFEST_HASH_PATTERN.test(entry.hash)
		) {
			throw new Error("cleanup journal has an invalid entry");
		}
		// Entry paths are validated lexically here. Recovery separately proves
		// the current no-symlink walk and captured parent identity; a hostile
		// post-crash symlink is unresolved state, not a malformed journal.
		const source = resolveRepoPath(targetDir, entry.source, "cleanup journal source");
		const quarantine = resolveRepoPath(targetDir, entry.quarantine, "cleanup journal quarantine");
		if (path.dirname(source) !== path.dirname(quarantine)) {
			throw new Error("cleanup journal source and quarantine must share a parent");
		}
		if (!MANIFEST_QUARANTINE_BASENAME.test(path.posix.basename(entry.quarantine))) {
			throw new Error("cleanup journal has an invalid quarantine name");
		}
	}
	return parsed;
}

const CLEANUP_JOURNAL_QUARANTINE_README = `STDD cleanup journal quarantine — do not load

This owner-private, same-device directory outside the checkout contains a
zero-length tombstone from an identity-bound cleanup journal settlement.
STDD never deletes quarantine pathnames automatically because a final
basename can be replaced concurrently. Inspect and remove this directory
manually when convenient.
`;

function openCleanupJournalQuarantine(targetDir, sourceDevice, currentUid) {
	const realRepo = fs.realpathSync(targetDir);
	const candidates = [...new Set([fs.realpathSync(path.resolve(os.tmpdir())), path.dirname(realRepo)])];
	let lastError = null;
	for (const candidate of candidates) {
		if (candidate === realRepo || candidate.startsWith(`${realRepo}${path.sep}`)) continue;
		let tempDescriptor = null;
		let quarantineDescriptor = null;
		try {
			tempDescriptor = fs.openSync(
				candidate,
				fs.constants.O_RDONLY | fs.constants.O_DIRECTORY | fs.constants.O_NOFOLLOW,
			);
			const tempIdentity = fs.fstatSync(tempDescriptor);
			const heldTemp = `/proc/self/fd/${tempDescriptor}`;
			if (
				!tempIdentity.isDirectory() ||
				tempIdentity.dev !== sourceDevice ||
				fs.realpathSync(heldTemp) !== candidate
			) {
				fs.closeSync(tempDescriptor);
				continue;
			}
			const heldQuarantinePath = fs.mkdtempSync(path.join(heldTemp, "stdd-cleanup-journal-quarantine-"));
			const quarantinePath = fs.realpathSync(heldQuarantinePath);
			if (path.dirname(quarantinePath) !== candidate) {
				throw new Error("cleanup journal quarantine escaped its held temp parent");
			}
			fs.chmodSync(heldQuarantinePath, 0o700);
			fs.writeFileSync(path.join(heldQuarantinePath, "README.txt"), CLEANUP_JOURNAL_QUARANTINE_README, {
				mode: 0o600,
				flag: "wx",
			});
			quarantineDescriptor = fs.openSync(
				heldQuarantinePath,
				fs.constants.O_RDONLY | fs.constants.O_DIRECTORY | fs.constants.O_NOFOLLOW,
			);
			const quarantineIdentity = fs.fstatSync(quarantineDescriptor);
			const heldQuarantine = `/proc/self/fd/${quarantineDescriptor}`;
			if (
				!quarantineIdentity.isDirectory() ||
				quarantineIdentity.dev !== sourceDevice ||
				(quarantineIdentity.mode & 0o777) !== 0o700 ||
				(currentUid !== null && quarantineIdentity.uid !== currentUid) ||
				fs.realpathSync(heldQuarantine) !== quarantinePath
			) {
				throw new Error("cleanup journal quarantine identity changed while it was opened");
			}
			return {
				tempDescriptor,
				tempIdentity,
				quarantineDescriptor,
				quarantineIdentity,
				heldQuarantine,
			};
		} catch (err) {
			lastError = err;
			if (quarantineDescriptor !== null) fs.closeSync(quarantineDescriptor);
			if (tempDescriptor !== null) fs.closeSync(tempDescriptor);
		}
	}
	throw new Error(
		`cleanup journal needs an owner-private same-device quarantine outside the checkout${
			lastError ? `: ${lastError.message}` : ""
		}`,
	);
}

function clearCleanupJournal(targetDir) {
	if (process.platform !== "linux") {
		throw new Error(
			"cleanup journal clear needs Linux held-parent support; the journal was preserved for manual recovery",
		);
	}
	let heldDirectory = null;
	let journalDescriptor = null;
	let quarantine = null;
	let tombstonePath = null;
	const currentUid = typeof process.getuid === "function" ? process.getuid() : null;
	const safeJournal = (stat) =>
		stat.isFile() &&
		!stat.isSymbolicLink() &&
		stat.nlink === 1 &&
		(stat.mode & 0o777) === 0o600 &&
		(currentUid === null || stat.uid === currentUid);
	try {
		heldDirectory = openHeldLinuxRepoDirectory(targetDir, ".stdd", "cleanup journal parent");
		const heldJournalPath = path.join(heldDirectory.heldPath, path.basename(CLEANUP_JOURNAL_REL));
		let before;
		try {
			before = fs.lstatSync(heldJournalPath);
		} catch (err) {
			if (err.code === "ENOENT") return;
			throw err;
		}
		journalDescriptor = fs.openSync(heldJournalPath, fs.constants.O_RDWR | fs.constants.O_NOFOLLOW);
		const opened = fs.fstatSync(journalDescriptor);
		const atOpen = fs.lstatSync(heldJournalPath);
		const parentAtOpen = fs.fstatSync(heldDirectory.descriptor);
		if (
			!safeJournal(before) ||
			!safeJournal(opened) ||
			!safeJournal(atOpen) ||
			!samePublicationObservation(before, opened) ||
			!samePublicationObservation(opened, atOpen) ||
			!sameFileIdentity(heldDirectory.identity, parentAtOpen)
		) {
			throw new Error("cleanup journal changed before it could be cleared");
		}

		// Allocate and bind a same-device quarantine before zeroization. If no
		// outside-checkout parent can support an atomic inode move, preserve
		// the still-readable WAL for deterministic recovery.
		quarantine = openCleanupJournalQuarantine(targetDir, opened.dev, currentUid);
		const zeroes = Buffer.alloc(64 * 1024);
		let remaining = opened.size;
		while (remaining > 0) {
			const length = Math.min(remaining, zeroes.length);
			const written = fs.writeSync(journalDescriptor, zeroes, 0, length, null);
			if (written <= 0) throw new Error("cleanup journal could not be overwritten before clear");
			remaining -= written;
		}
		fs.fsyncSync(journalDescriptor);
		fs.ftruncateSync(journalDescriptor, 0);
		fs.fsyncSync(journalDescriptor);
		const wiped = fs.fstatSync(journalDescriptor);
		const wipedAtSource = fs.lstatSync(heldJournalPath);
		if (
			!safeJournal(wiped) ||
			wiped.size !== 0 ||
			!sameFileIdentity(opened, wiped) ||
			!samePublicationObservation(wiped, wipedAtSource)
		) {
			throw new Error("cleanup journal changed while its bytes were cleared");
		}

		tombstonePath = path.join(
			quarantine.heldQuarantine,
			`cleanup-journal-${randomBytes(16).toString("hex")}.tombstone`,
		);
		const beforeMove = fs.fstatSync(journalDescriptor);
		const sourceBeforeMove = fs.lstatSync(heldJournalPath);
		if (
			!samePublicationObservation(wiped, beforeMove) ||
			!samePublicationObservation(beforeMove, sourceBeforeMove)
		) {
			throw new Error("cleanup journal changed before its quarantine move");
		}
		fs.renameSync(heldJournalPath, tombstonePath);
		fs.fsyncSync(heldDirectory.descriptor);
		fs.fsyncSync(quarantine.quarantineDescriptor);

		const afterMove = fs.fstatSync(journalDescriptor);
		const atTombstone = fs.lstatSync(tombstonePath);
		const quarantineAfterMove = fs.fstatSync(quarantine.quarantineDescriptor);
		const tempAfterMove = fs.fstatSync(quarantine.tempDescriptor);
		if (
			!safeJournal(afterMove) ||
			!safeJournal(atTombstone) ||
			!samePublicationPayload(beforeMove, afterMove) ||
			!samePublicationObservation(afterMove, atTombstone) ||
			!sameFileIdentity(quarantine.quarantineIdentity, quarantineAfterMove) ||
			!sameFileIdentity(quarantine.tempIdentity, tempAfterMove)
		) {
			throw new Error("cleanup journal changed while it was cleared");
		}
		try {
			fs.lstatSync(heldJournalPath);
			throw new Error("cleanup journal changed while it was cleared");
		} catch (err) {
			if (err.code !== "ENOENT") throw err;
		}
		const logicalParent = fs.lstatSync(heldDirectory.logicalPath);
		const heldParent = fs.fstatSync(heldDirectory.descriptor);
		if (
			!sameFileIdentity(heldDirectory.identity, logicalParent) ||
			!sameFileIdentity(heldDirectory.identity, heldParent)
		) {
			throw new Error("cleanup journal parent changed while the journal was cleared");
		}

		fs.closeSync(journalDescriptor);
		journalDescriptor = null;
		const tombstoneAfterClose = fs.lstatSync(tombstonePath);
		const quarantineAfterClose = fs.fstatSync(quarantine.quarantineDescriptor);
		const tempAfterClose = fs.fstatSync(quarantine.tempDescriptor);
		if (
			!safeJournal(tombstoneAfterClose) ||
			!samePublicationObservation(afterMove, tombstoneAfterClose) ||
			!sameFileIdentity(quarantine.quarantineIdentity, quarantineAfterClose) ||
			!sameFileIdentity(quarantine.tempIdentity, tempAfterClose)
		) {
			throw new Error("cleanup journal changed while it was cleared");
		}
		try {
			fs.lstatSync(heldJournalPath);
			throw new Error("cleanup journal changed while it was cleared");
		} catch (err) {
			if (err.code !== "ENOENT") throw err;
		}
	} catch (err) {
		if (err.code === "ENOENT" || err.code === "ELOOP") {
			throw new Error("cleanup journal changed while it was cleared");
		}
		throw err;
	} finally {
		if (journalDescriptor !== null) {
			try {
				fs.closeSync(journalDescriptor);
			} catch {
				// The exact journal inode remains preserved; never chase a basename.
			}
		}
		if (quarantine !== null) {
			try {
				fs.closeSync(quarantine.quarantineDescriptor);
			} catch {}
			try {
				fs.closeSync(quarantine.tempDescriptor);
			} catch {}
		}
		if (heldDirectory !== null) {
			try {
				fs.closeSync(heldDirectory.descriptor);
			} catch {
				// The held parent has already proved success or an indeterminate clear.
			}
		}
	}
}

function inspectCleanupEntryState(targetDir, entry) {
	try {
		const source = resolveWritableRepoPath(targetDir, entry.source, "cleanup state source");
		const quarantine = resolveWritableRepoPath(targetDir, entry.quarantine, "cleanup state quarantine");
		const parentPath = path.dirname(source);
		const parent = fs.lstatSync(parentPath);
		if (
			String(parent.dev) !== entry.parentDev ||
			String(parent.ino) !== entry.parentIno ||
			!parent.isDirectory() ||
			parent.isSymbolicLink()
		) {
			throw new Error("logical parent no longer maps to the journaled directory identity");
		}
		const inspectPath = (candidate) => {
			let descriptor = null;
			try {
				const before = fs.lstatSync(candidate);
				if (before.isSymbolicLink() || !before.isFile()) {
					throw new Error("is not a non-symlinked regular file");
				}
				descriptor = fs.openSync(candidate, fs.constants.O_RDONLY | fs.constants.O_NOFOLLOW);
				const opened = fs.fstatSync(descriptor);
				const bytes = fs.readFileSync(descriptor);
				const after = fs.lstatSync(candidate);
				if (!opened.isFile() || !sameFileIdentity(before, opened) || !sameFileIdentity(opened, after)) {
					throw new Error("changed while its identity was verified");
				}
				return {
					exists: true,
					exactIdentity: String(opened.dev) === entry.fileDev && String(opened.ino) === entry.fileIno,
					hash: sha256(bytes),
				};
			} catch (err) {
				if (err.code === "ENOENT") return { exists: false };
				throw err;
			} finally {
				if (descriptor !== null) {
					try {
						fs.closeSync(descriptor);
					} catch {}
				}
			}
		};
		const sourceState = inspectPath(source);
		const quarantineState = inspectPath(quarantine);
		const parentAfter = fs.lstatSync(parentPath);
		if (!sameFileIdentity(parent, parentAfter)) {
			throw new Error("logical parent changed while cleanup state was inspected");
		}
		if (quarantineState.exists && quarantineState.exactIdentity && quarantineState.hash === entry.hash) {
			return {
				kind: "quarantined",
				keepSource: sourceState.exists,
			};
		}
		if (
			sourceState.exists &&
			sourceState.exactIdentity &&
			sourceState.hash === entry.hash &&
			!quarantineState.exists
		) {
			return { kind: "restored" };
		}
		throw new Error(
			`cannot prove the journaled file inode at either path (source=${
				sourceState.exists ? "other" : "missing"
			}, quarantine=${quarantineState.exists ? "other" : "missing"})`,
		);
	} catch (err) {
		return { kind: "unresolved", reason: err.message };
	}
}

function cleanupJournalCommitted(targetDir, journal) {
	try {
		const manifest = readManifestDocument(targetDir);
		if (!manifest) return false;
		return journal.entries.every((entry) => {
			const state = inspectCleanupEntryState(targetDir, entry);
			return (
				entry.phase === "quarantined" &&
				state.kind === "quarantined" &&
				state.keepSource === entry.keepSource &&
				Object.hasOwn(manifest.files, entry.quarantine) &&
				manifest.files[entry.quarantine] === entry.hash &&
				(entry.keepSource
					? Object.hasOwn(manifest.files, entry.source) && manifest.files[entry.source] === entry.hash
					: !Object.hasOwn(manifest.files, entry.source))
			);
		});
	} catch {
		return false;
	}
}

function rollbackCleanupEntryThroughHeldParent(targetDir, entry) {
	if (process.platform !== "linux") {
		throw new Error(
			"safe cleanup rollback needs Linux held-parent support; the journal was preserved for manual recovery",
		);
	}
	const source = resolveWritableRepoPath(targetDir, entry.source, "cleanup rollback source");
	const quarantine = resolveWritableRepoPath(targetDir, entry.quarantine, "cleanup rollback quarantine");
	const parentPath = path.dirname(source);
	if (parentPath !== path.dirname(quarantine)) {
		throw new Error("cleanup rollback paths no longer share one parent");
	}
	let parentDescriptor = null;
	try {
		parentDescriptor = fs.openSync(
			parentPath,
			fs.constants.O_RDONLY | fs.constants.O_DIRECTORY | fs.constants.O_NOFOLLOW,
		);
		const parent = fs.fstatSync(parentDescriptor);
		if (
			!parent.isDirectory() ||
			String(parent.dev) !== entry.parentDev ||
			String(parent.ino) !== entry.parentIno
		) {
			throw new Error("logical parent no longer maps to the journaled directory identity");
		}
		const heldParent = `/proc/self/fd/${parentDescriptor}`;
		// Fail before mutation when procfs cannot supply the stable pathname
		// bridge used by Node's synchronous rename API.
		fs.realpathSync(heldParent);
		const heldSource = path.join(heldParent, path.basename(source));
		const heldQuarantine = path.join(heldParent, path.basename(quarantine));
		const inspectHeld = (candidate) => {
			let descriptor = null;
			try {
				const before = fs.lstatSync(candidate);
				if (before.isSymbolicLink() || !before.isFile()) {
					throw new Error("held cleanup path is not a non-symlinked regular file");
				}
				descriptor = fs.openSync(candidate, fs.constants.O_RDONLY | fs.constants.O_NOFOLLOW);
				const opened = fs.fstatSync(descriptor);
				const bytes = fs.readFileSync(descriptor);
				const after = fs.lstatSync(candidate);
				if (!opened.isFile() || !sameFileIdentity(before, opened) || !sameFileIdentity(opened, after)) {
					throw new Error("held cleanup path changed while it was verified");
				}
				return {
					exists: true,
					exact:
						String(opened.dev) === entry.fileDev &&
						String(opened.ino) === entry.fileIno &&
						sha256(bytes) === entry.hash,
				};
			} catch (err) {
				if (err.code === "ENOENT") return { exists: false, exact: false };
				throw err;
			} finally {
				if (descriptor !== null) {
					try {
						fs.closeSync(descriptor);
					} catch {}
				}
			}
		};
		const sourceBefore = inspectHeld(heldSource);
		const quarantineBefore = inspectHeld(heldQuarantine);
		if (sourceBefore.exact && !quarantineBefore.exists) {
			// Already restored by an earlier partial rollback.
		} else if (!sourceBefore.exists && quarantineBefore.exact) {
			fs.renameSync(heldQuarantine, heldSource);
		} else {
			throw new Error(
				sourceBefore.exists
					? "both the quarantine and another source object are live"
					: "the exact journaled inode is not available at its quarantine",
			);
		}
		const sourceAfter = inspectHeld(heldSource);
		const quarantineAfter = inspectHeld(heldQuarantine);
		const heldParentAfter = fs.fstatSync(parentDescriptor);
		if (!sourceAfter.exact || quarantineAfter.exists || !sameFileIdentity(parent, heldParentAfter)) {
			throw new Error("held-parent rollback did not restore the exact journaled inode");
		}
		const logicalParentAfter = fs.lstatSync(parentPath);
		if (
			logicalParentAfter.isSymbolicLink() ||
			!logicalParentAfter.isDirectory() ||
			!sameFileIdentity(parent, logicalParentAfter)
		) {
			throw new Error(
				"logical parent changed during held-parent rollback; no outside path was modified",
			);
		}
	} finally {
		if (parentDescriptor !== null) {
			try {
				fs.closeSync(parentDescriptor);
			} catch {}
		}
	}
}

function rollbackCleanupJournal(targetDir, journal) {
	const unresolved = [];
	for (const entry of [...journal.entries].reverse()) {
		try {
			rollbackCleanupEntryThroughHeldParent(targetDir, entry);
			entry.phase = "planned";
			entry.keepSource = false;
			entry.reason = "";
		} catch (err) {
			entry.phase = "unresolved";
			entry.reason = err.message;
			unresolved.push(`${entry.source}: ${err.message}`);
		}
	}
	if (unresolved.length > 0) {
		try {
			writeCleanupJournal(targetDir, journal);
		} catch (err) {
			unresolved.push(`journal phase update: ${err.message}`);
		}
	}
	return unresolved;
}

function recoverCleanupJournal(targetDir) {
	let journal;
	try {
		journal = readCleanupJournal(targetDir);
	} catch (err) {
		fail(`${CLEANUP_JOURNAL_REL} is invalid — ${err.message}; inspect it before retrying init`);
	}
	if (!journal) return;
	if (cleanupJournalCommitted(targetDir, journal)) {
		clearCleanupJournal(targetDir);
		return;
	}
	const unresolved = rollbackCleanupJournal(targetDir, journal);
	if (unresolved.length > 0) {
		fail(
			`${CLEANUP_JOURNAL_REL} has unresolved cleanup state — ${unresolved.join(
				"; ",
			)}; restore the named paths before retrying init`,
		);
	}
	clearCleanupJournal(targetDir);
}

function publishManifestDurably(targetDir, manifest, state) {
	const manifestPath = resolveRepoPath(targetDir, ".stdd/manifest.json", "manifest path");
	if (process.platform !== "linux") {
		throw new Error(
			"secure manifest publication is unsupported on this platform because no held-parent pathname bridge is available",
		);
	}
	publishHeldParentFile({
		openDirectory: () => openHeldLinuxRepoDirectory(targetDir, ".stdd", "manifest parent"),
		logicalTargetPath: manifestPath,
		content: `${JSON.stringify(manifest, null, "\t")}\n`,
		mode: 0o600,
		tempPrefix: ".manifest-",
		identityError: "manifest parent or published identity changed during durable publication",
		onRenameAttempt: () => {
			state.renameAttempted = true;
		},
	});
	state.durable = true;
}

const MANIFEST_QUARANTINE_BASENAME = /^\.stdd-cleanup-[0-9a-f]{32}\.tmp$/;

/**
 * Read one manifest-tracked output without following a symlink or trusting a
 * check-then-read path race. Callers receive a finding, never a filesystem
 * exception. `missing` remains distinct so check keeps its established hint.
 */
function inspectManifestOutput(targetDir, file) {
	let filePath;
	try {
		filePath = resolveWritableRepoPath(targetDir, file, `manifest path ${JSON.stringify(file)}`);
	} catch (err) {
		return { kind: "invalid", reason: err.message };
	}

	let before;
	try {
		before = fs.lstatSync(filePath);
	} catch (err) {
		if (err.code === "ENOENT") return { kind: "missing" };
		return { kind: "invalid", reason: `metadata could not be read safely: ${err.message}` };
	}
	if (before.isSymbolicLink()) {
		return { kind: "invalid", reason: "is a symlink, not a regular file" };
	}
	if (!before.isFile()) {
		return {
			kind: "invalid",
			reason: before.isDirectory() ? "is a directory, not a regular file" : "is a non-regular file",
		};
	}

	let descriptor = null;
	let result;
	try {
		descriptor = fs.openSync(filePath, fs.constants.O_RDONLY | fs.constants.O_NOFOLLOW);
		const opened = fs.fstatSync(descriptor);
		if (!opened.isFile()) {
			result = {
				kind: "invalid",
				reason: "was replaced during inspection with a non-regular file",
			};
		} else {
			const bytes = fs.readFileSync(descriptor);
			const after = fs.lstatSync(filePath);
			// Re-run the path walk after reading: a parent directory may have
			// become a symlink after the initial resolution.
			resolveWritableRepoPath(targetDir, file, `manifest path ${JSON.stringify(file)}`);
			const realRoot = fs.realpathSync(targetDir);
			const realFile = fs.realpathSync(filePath);
			const fromRoot = path.relative(realRoot, realFile);
			const escaped =
				fromRoot === ".." || fromRoot.startsWith(`..${path.sep}`) || path.isAbsolute(fromRoot);
			const finalStat = fs.lstatSync(filePath);
			if (
				escaped ||
				after.isSymbolicLink() ||
				!after.isFile() ||
				!sameFileIdentity(opened, after) ||
				finalStat.isSymbolicLink() ||
				!finalStat.isFile() ||
				!sameFileIdentity(opened, finalStat)
			) {
				result = {
					kind: "invalid",
					reason: escaped
						? "resolved outside the repository during inspection"
						: "was replaced during inspection",
				};
			} else {
				result = {
					kind: "ok",
					filePath,
					bytes,
					identity: opened,
					realParentPath: path.dirname(realFile),
				};
			}
		}
	} catch (err) {
		result = {
			kind: "invalid",
			reason:
				err.code === "ENOENT"
					? "was replaced or removed during inspection"
					: `could not be read safely: ${err.message}`,
		};
	} finally {
		if (descriptor !== null) {
			try {
				fs.closeSync(descriptor);
			} catch (err) {
				result = {
					kind: "invalid",
					reason: `could not be closed safely after reading: ${err.message}`,
				};
			}
		}
	}
	return result;
}

/**
 * Quarantine and remove a verified output through a held parent directory.
 * Linux procfs gives pathname operations a stable dirfd-like anchor. Other
 * runtimes fail closed and preserve the output for manual cleanup.
 */
function removeInspectedManifestOutput(inspected, expectedHash, quarantineName) {
	if (process.platform !== "linux") {
		return { removed: false, reason: "atomic parent-bound cleanup is unavailable on this platform" };
	}
	let parentDescriptor = null;
	let fileDescriptor = null;
	let quarantinePath = null;
	let sourcePath = null;
	let renamed = false;
	const settleRenamedQuarantine = (cause) => {
		try {
			const sourceExists = fs.existsSync(sourcePath);
			if (!sourceExists) {
				let rolledBack = false;
				try {
					fs.renameSync(quarantinePath, sourcePath);
					rolledBack = true;
					const restored = fs.lstatSync(sourcePath);
					if (
						restored.isFile() &&
						!restored.isSymbolicLink() &&
						sameFileIdentity(inspected.identity, restored)
					) {
						return {
							removed: false,
							reason: "the quarantined output was restored after a cleanup verification failure",
							error: cause,
						};
					}
				} catch {
					// The caller owns a durable journal containing both exact
					// paths and identities and will settle or block.
				}
				if (rolledBack) {
					return {
						removed: false,
						reason: "cleanup rollback restored a changed object at the original path",
					};
				}
			}
			return {
				removed: true,
				quarantineName,
				keepSource: fs.existsSync(sourcePath),
				warning: `cleanup verification failed after quarantine: ${cause.message}`,
			};
		} catch (err) {
			// Settlement is deliberately total: even hostile probe faults are
			// converted into durable unresolved state by the caller.
			return {
				removed: false,
				unresolved: true,
				quarantineName,
				reason: `cleanup settlement could not inspect its paths: ${err.message}`,
			};
		}
	};
	try {
		const parentPath = path.dirname(inspected.filePath);
		parentDescriptor = fs.openSync(
			parentPath,
			fs.constants.O_RDONLY | fs.constants.O_DIRECTORY | fs.constants.O_NOFOLLOW,
		);
		const heldParent = `/proc/self/fd/${parentDescriptor}`;
		if (fs.realpathSync(heldParent) !== inspected.realParentPath) {
			return { removed: false, reason: "parent directory was replaced after inspection" };
		}
		sourcePath = path.join(heldParent, path.basename(inspected.filePath));
		fileDescriptor = fs.openSync(sourcePath, fs.constants.O_RDONLY | fs.constants.O_NOFOLLOW);
		const current = fs.fstatSync(fileDescriptor);
		if (!current.isFile() || !sameFileIdentity(inspected.identity, current)) {
			return { removed: false, reason: "output was replaced after inspection" };
		}
		if (sha256(fs.readFileSync(fileDescriptor)) !== expectedHash) {
			return { removed: false, reason: "output changed after inspection" };
		}

		quarantinePath = path.join(heldParent, quarantineName);
		fs.renameSync(sourcePath, quarantinePath);
		renamed = true;
		const quarantined = fs.lstatSync(quarantinePath);
		if (
			quarantined.isSymbolicLink() ||
			!quarantined.isFile() ||
			!sameFileIdentity(current, quarantined)
		) {
			return settleRenamedQuarantine(new Error("output was replaced at the quarantine boundary"));
		}
		if (fs.realpathSync(heldParent) !== inspected.realParentPath) {
			return settleRenamedQuarantine(
				new Error("generated cleanup parent directory changed during quarantine"),
			);
		}
		quarantinePath = null;
		return { removed: true, quarantineName };
	} catch (err) {
		if (renamed) return settleRenamedQuarantine(err);
		return { removed: false, reason: `parent-bound cleanup failed: ${err.message}`, error: err };
	} finally {
		if (fileDescriptor !== null) {
			try {
				fs.closeSync(fileDescriptor);
			} catch {
				// The path operation has already settled; descriptor cleanup is best effort.
			}
		}
		if (parentDescriptor !== null) {
			try {
				fs.closeSync(parentDescriptor);
			} catch {
				// The path operation has already settled; descriptor cleanup is best effort.
			}
		}
	}
}

/**
 * `--capabilities <list>`: write the full profile into the user-owned
 * config — named capabilities on, every other known one off. Other config
 * keys survive untouched.
 */
function readConfigForWrite(targetDir) {
	const configPath = resolveWritableRepoPath(targetDir, ".stdd/config.json", "config path");
	let parsed = { ...DEFAULT_CONFIG };
	if (fs.existsSync(configPath)) {
		try {
			parsed = JSON.parse(fs.readFileSync(configPath, "utf8"));
		} catch (err) {
			fail(`.stdd/config.json is not valid JSON: ${err.message}`);
		}
	}
	try {
		mergeConfig(parsed);
	} catch (err) {
		fail(`.stdd/config.json: ${err.message}`);
	}
	return { configPath, parsed };
}

function writeCapabilities(targetDir, list) {
	const { configPath, parsed } = readConfigForWrite(targetDir);
	parsed.capabilities = Object.fromEntries(KNOWN_CAPABILITIES.map((c) => [c, list.includes(c)]));
	fs.writeFileSync(configPath, `${JSON.stringify(parsed, null, "\t")}\n`);
}

/** Set review.via (and optionally the budget) in the user-owned config,
 * preserving every other key. */
function writeReviewVia(targetDir, via, maxRounds = null) {
	const { configPath, parsed } = readConfigForWrite(targetDir);
	parsed.review = {
		...(parsed.review ?? {}),
		via,
		...(maxRounds !== null ? { maxRounds } : {}),
	};
	fs.writeFileSync(configPath, `${JSON.stringify(parsed, null, "\t")}\n`);
}

/**
 * `--interview`: one question at a time, the recommended answer first —
 * an empty answer takes it. Piped answers work; a stream that ends early
 * resolves every remaining question to its default.
 */
function makePrompter() {
	const rl = createInterface({ input: process.stdin, output: process.stdout });
	// Own line queue instead of rl.question: piped answers arrive in one
	// burst, and lines emitted while no question is pending would be lost.
	const lines = [];
	const waiters = [];
	let closed = false;
	rl.on("line", (line) => {
		const waiter = waiters.shift();
		if (waiter) waiter(line);
		else lines.push(line);
	});
	rl.on("close", () => {
		closed = true;
		while (waiters.length > 0) waiters.shift()("");
	});
	const readLine = () => {
		if (lines.length > 0) return Promise.resolve(lines.shift());
		if (closed) return Promise.resolve("");
		return new Promise((resolve) => waiters.push(resolve));
	};
	const ask = async (question, def) => {
		process.stdout.write(question);
		const answer = (await readLine()).trim();
		return answer === "" ? def : answer;
	};
	const yes = async (question, def) =>
		/^y/i.test(await ask(`${question} ${def ? "[Y/n]" : "[y/N]"} `, def ? "y" : "n"));
	return { ask, yes, close: () => rl.close() };
}

/** The reviewer-route question, shared by init --interview and configure. */
async function askReviewVia(ask, close, def) {
	const via = await ask(`Independent reviewer route (${REVIEW_VIAS.join("/")}) [${def}]: `, def);
	if (!REVIEW_VIAS.includes(via)) {
		close();
		fail(`unknown review route "${via}" (known: ${REVIEW_VIAS.join(", ")})`);
	}
	return via;
}

function recommendedReviewVia(tools, capabilities) {
	if (capabilities.crossCli) {
		return getAgentAdapter(tools[0]).crossCliReviewVia;
	}
	if (capabilities.subagents) return "subagent";
	return DEFAULT_CONFIG.review.via;
}

async function interview() {
	const { ask, yes, close } = makePrompter();

	console.log("stdd init — one question at a time; an empty answer takes the recommended default\n");
	const toolsAnswer = await ask(
		`Agents to compile for (${KNOWN_TOOLS.join(", ")}) [${KNOWN_TOOLS.join(",")}]: `,
		KNOWN_TOOLS.join(","),
	);
	const tools = toolsAnswer
		.split(",")
		.map((t) => t.trim())
		.filter(Boolean);
	try {
		validateAdapterSelection("tools", tools, KNOWN_TOOLS, { nonEmpty: true });
	} catch (err) {
		close();
		fail(err.message);
	}
	const capabilitiesList = [];
	if (await yes("Can agents dispatch subagents?", true)) capabilitiesList.push("subagents");
	if (await yes("May selected agent CLIs invoke a second reviewer CLI?", false))
		capabilitiesList.push("crossCli");
	if (await yes("Are isolated git worktrees available?", true)) capabilitiesList.push("worktrees");
	const capabilities = Object.fromEntries(
		KNOWN_CAPABILITIES.map((capability) => [capability, capabilitiesList.includes(capability)]),
	);
	// The first selected native host is the driver for the repository-level
	// default. Generated skills still carry a per-host explicit override.
	const reviewVia = await askReviewVia(ask, close, recommendedReviewVia(tools, capabilities));
	const ci = (await yes("Install the GitHub Actions gate (stdd check + PR evidence)?", true))
		? ["github"]
		: [];
	const hooks = await yes("Install the pre-push hook (stdd check — fast, offline)?", true);
	const sessionHook =
		tools.length > 0 ? await yes("Wire native agent session hooks (stdd status --local)?", true) : false;
	const stopHook =
		tools.length > 0
			? await yes("Wire native agent stop integrations (gate or corrective continuation)?", false)
			: false;
	close();
	const hasDispatch = capabilitiesList.includes("subagents") || capabilitiesList.includes("crossCli");
	if (
		hasDispatch &&
		(reviewVia === "codex" || reviewVia === "claude") &&
		!capabilitiesList.includes("crossCli")
	) {
		fail(
			`review route "${reviewVia}" needs the crossCli capability — answer y to cross-CLI or pick subagent`,
		);
	}
	if (hasDispatch && reviewVia === "subagent" && !capabilitiesList.includes("subagents")) {
		fail(
			`review route "subagent" needs the subagents capability — answer y to subagents or pick another route`,
		);
	}
	return {
		tools,
		ci,
		hooks,
		sessionHook,
		stopHook,
		capabilitiesList,
		reviewVia,
	};
}

/**
 * `stdd configure` — the interview again, over an existing install:
 * current values are the defaults, only the capability profile and the
 * review route are edited, every other config key is preserved, and the
 * same generated targets (remembered in the manifest) are recompiled.
 * Never changes CI target selection or removes hook files. A remembered Stop
 * hook is maintained, and --stop-hook is the explicit opt-in that may add it.
 */
async function configure(targetDir, opts) {
	requireHeldParentPublicationPlatform();
	const configPath = path.join(targetDir, ".stdd", "config.json");
	if (!fs.existsSync(configPath)) {
		fail(
			"no .stdd/config.json here — `stdd configure` edits an existing install; run `stdd init` first",
		);
	}
	const config = loadConfig(targetDir);
	recoverCleanupJournal(targetDir);
	let targets = null;
	let manifestFiles = null;
	let manifest = null;
	try {
		manifest = readManifestDocument(targetDir);
	} catch (err) {
		fail(`.stdd/manifest.json ${err.message}`);
	}
	if (manifest && Object.hasOwn(manifest, "targets")) {
		targets = manifest.targets;
	} else if (manifest) {
		manifestFiles = Object.keys(manifest.files);
	}
	// installs made before targets were remembered: infer what the previous
	// init actually GENERATED from manifest.files — live directories lie (a
	// stray empty .claude/skills must not smuggle claude in) and an
	// inferred blank would make the stale-file cleanup delete the CI
	// workflow. The filesystem is the last resort with no usable manifest;
	// hook files and settings entries are user-owned, never
	// manifest-tracked, so they are always read from their files.
	if (!targets) {
		const tools = [];
		const ci = [];
		const skillRootCounts = new Map();
		for (const adapter of Object.values(AGENT_ADAPTERS)) {
			skillRootCounts.set(adapter.skillRoot, (skillRootCounts.get(adapter.skillRoot) ?? 0) + 1);
		}
		if (manifestFiles) {
			for (const adapter of Object.values(AGENT_ADAPTERS)) {
				const ownsDistinctSkillRoot = skillRootCounts.get(adapter.skillRoot) === 1;
				if (
					manifestFiles.includes(adapter.snippetFile) ||
					(ownsDistinctSkillRoot &&
						manifestFiles.some((file) => file.startsWith(`${adapter.skillRoot}/`)))
				) {
					tools.push(adapter.id);
				}
			}
			for (const adapter of Object.values(CI_ADAPTERS)) {
				if (adapter.outputFile && manifestFiles.includes(adapter.outputFile)) ci.push(adapter.id);
			}
		} else {
			for (const adapter of Object.values(AGENT_ADAPTERS)) {
				const ownsDistinctSkillRoot = skillRootCounts.get(adapter.skillRoot) === 1;
				if (
					fs.existsSync(path.join(targetDir, adapter.snippetFile)) ||
					(ownsDistinctSkillRoot && fs.existsSync(path.join(targetDir, adapter.skillRoot)))
				) {
					tools.push(adapter.id);
				}
			}
			for (const adapter of Object.values(CI_ADAPTERS)) {
				if (adapter.outputFile && fs.existsSync(path.join(targetDir, adapter.outputFile))) {
					ci.push(adapter.id);
				}
			}
		}
		let settingsText = "";
		for (const relative of new Set(Object.values(AGENT_ADAPTERS).map((adapter) => adapter.hooksFile))) {
			try {
				settingsText += fs.readFileSync(path.join(targetDir, relative), "utf8");
			} catch {
				// absent agent settings do not imply hooks
			}
		}
		targets = {
			tools: tools.length > 0 ? tools : ["claude"],
			ci,
			hooks: fs.existsSync(path.join(targetDir, ".stdd", "hooks", "pre-push")),
			sessionHook:
				settingsText.includes("stdd status") ||
				(settingsText.includes("STDD managed Pi lifecycle extension") &&
					settingsText.includes('pi.on("session_start"')),
			stopHook:
				settingsText.includes("stdd stop-hook") ||
				(settingsText.includes("STDD managed Pi lifecycle extension") &&
					settingsText.includes('pi.on("agent_settled"')),
		};
	}
	let capabilitiesList = opts.capabilitiesList ?? null;
	let reviewVia = opts.reviewVia ?? null;
	let maxRounds = opts.maxRounds ?? null;
	let stopHook = Boolean(opts.stopHook);
	const interactive = !capabilitiesList && !reviewVia && maxRounds === null && !stopHook;
	if (interactive) {
		const { ask, yes, close } = makePrompter();
		console.log("stdd configure — one question at a time; an empty answer keeps the current value\n");
		capabilitiesList = [];
		if (await yes("Can agents dispatch subagents?", config.capabilities.subagents))
			capabilitiesList.push("subagents");
		if (await yes("May selected agent CLIs invoke a second reviewer CLI?", config.capabilities.crossCli))
			capabilitiesList.push("crossCli");
		if (await yes("Are isolated git worktrees available?", config.capabilities.worktrees))
			capabilitiesList.push("worktrees");
		reviewVia = await askReviewVia(ask, close, config.review.via);
		const current = config.review.maxRounds ?? 0;
		const budgetAnswer = await ask(
			`Review budget — changes-requested rounds before refusal (0 = unlimited) [${current}]: `,
			String(current),
		);
		maxRounds = Number(budgetAnswer);
		if (!/^\d+$/.test(budgetAnswer) || !Number.isSafeInteger(maxRounds)) {
			close();
			fail("the review budget must be a non-negative safe integer (0 = unlimited)");
		}
		if (targets.tools.length > 0 && !targets.stopHook) {
			stopHook = await yes(
				"Wire native agent stop integrations (gate or corrective continuation)?",
				false,
			);
		}
		close();
	}
	// validate the combination BEFORE any write — no partial configuration
	const caps = capabilitiesList
		? Object.fromEntries(KNOWN_CAPABILITIES.map((c) => [c, capabilitiesList.includes(c)]))
		: config.capabilities;
	const via = reviewVia ?? config.review.via;
	const hasDispatch = caps.subagents || caps.crossCli;
	if (hasDispatch && (via === "codex" || via === "claude") && !caps.crossCli) {
		fail(`review.via "${via}" needs the crossCli capability — pick another route or enable crossCli`);
	}
	if (hasDispatch && via === "subagent" && !caps.subagents) {
		fail(
			`review.via "subagent" needs the subagents capability — pick another route or enable subagents`,
		);
	}
	const desiredStopHook = stopHook || targets.stopHook;
	const existingCi = targets.ci.filter((provider) => {
		const outputFile = CI_ADAPTERS[provider].outputFile;
		return outputFile === null || fs.existsSync(path.join(targetDir, outputFile));
	});
	init(targetDir, {
		tools: targets.tools,
		ci: existingCi,
		rememberedCiTargets: targets.ci,
		hooks: false,
		sessionHook: false,
		stopHook: desiredStopHook,
		rememberedHookTargets: {
			hooks: targets.hooks,
			sessionHook: targets.sessionHook,
			stopHook: desiredStopHook,
		},
		capabilitiesList: capabilitiesList ?? Object.keys(caps).filter((c) => caps[c]),
		reviewVia: via,
		reviewMaxRounds: maxRounds,
	});
}

const NO_PROJECT_LOG_METHOD_PREAMBLE = `# Repository policy: no project log

This repository sets \`projectLog.enabled\` to \`false\`. It does not use a
project log. Do not create or search dated decision, design, or deferred-work
archives. Keep current behavior in canonical docs; use PR descriptions and git
history for rationale and decisions.

This repository policy overrides generic project-log examples later in this
method.

---

`;

function renderInstalledMethod(source, projectLogEnabled) {
	return projectLogEnabled ? source : `${NO_PROJECT_LOG_METHOD_PREAMBLE}${source}`;
}

function init(targetDir, opts) {
	requireHeldParentPublicationPlatform();
	const { tools, ci, hooks, sessionHook, capabilitiesList } = opts;
	const stopHook = Boolean(opts.stopHook);
	const rememberedCiTargets = opts.rememberedCiTargets ?? ci;
	const rememberedHookTargets = opts.rememberedHookTargets ?? {
		hooks: Boolean(hooks),
		sessionHook: Boolean(sessionHook),
		stopHook,
	};
	const automationRunner = isStddSourceCheckout(targetDir) ? SOURCE_RUNNER : NPM_RUNNER;
	let stddDir;
	try {
		stddDir = resolveWritableRepoPath(targetDir, ".stdd", "stdd install path");
	} catch (err) {
		fail(err.message);
	}
	// Config is user-owned input. Validate it before loading playbooks,
	// inspecting manifests, or writing any generated/install state.
	const existingConfig = loadConfig(targetDir);
	// A previous crash or publish failure is settled before this run reads
	// dynamic paths below. An unprovable inode or parent identity blocks init
	// with the journal as the authoritative diagnostic.
	recoverCleanupJournal(targetDir);
	// Validate every repo-authored dynamic path before the first write. A
	// cloned repository must not turn `stdd init` into an arbitrary writer.
	const local = loadLocalPlaybooks(targetDir);
	const oldFiles = readManifestFiles(targetDir);
	// A same-name local recipe always replaces the kit recipe. Capability
	// filtering happens afterwards, so an inactive local override intentionally
	// leaves an optional skill absent instead of silently falling back to the kit.
	const capabilities = capabilitiesList
		? Object.fromEntries(KNOWN_CAPABILITIES.map((c) => [c, capabilitiesList.includes(c)]))
		: existingConfig.capabilities;
	const reviewVia =
		opts.reviewVia ??
		(capabilitiesList && (capabilities.crossCli || capabilities.subagents)
			? recommendedReviewVia(tools, capabilities)
			: null);
	const agentNeutralReviewVia = reviewVia ?? existingConfig.review.via;
	const applies = (pb) => {
		if (!pb.meta.requires) return true;
		if (!KNOWN_CAPABILITIES.includes(pb.meta.requires)) {
			fail(`playbook ${pb.file}: requires unknown capability "${pb.meta.requires}"`);
		}
		return capabilities[pb.meta.requires];
	};
	const compile = (pb, text) => {
		try {
			return compileCapabilities(text, capabilities);
		} catch (err) {
			fail(`playbook ${pb.file}: ${err.message}`);
		}
	};
	const localNames = new Set(local.map((pb) => pb.meta.name));
	const localActive = local.filter(applies);
	const kitActive = loadPlaybooks()
		.filter(applies)
		.filter((pb) => {
			if (!localNames.has(pb.meta.name)) return true;
			console.log(`local recipe overrides the kit playbook "${pb.meta.name}" (${pb.file})`);
			return false;
		});
	const activeNames = new Set([...kitActive, ...localActive].map((pb) => pb.meta.name));
	for (const name of MANDATORY_ROUTING_SKILLS) {
		if (!activeNames.has(name)) {
			fail(
				`mandatory routing skill "${name}" is inactive; capability profiles and local overrides must keep every managed agent route available`,
			);
		}
	}

	const installDirectory = openOrCreateHeldGeneratedParent(targetDir, ".stdd");
	fs.closeSync(installDirectory.descriptor);
	if (capabilitiesList) writeCapabilities(targetDir, capabilitiesList);
	if (reviewVia) writeReviewVia(targetDir, reviewVia, opts.reviewMaxRounds ?? null);
	// The previous run's manifest: files it generated that this profile no
	// longer produces are removed at the end — only when still byte-identical.
	// Every generated file is recorded here (repo-relative path → content
	// hash) and written to .stdd/manifest.json, so check/doctor can detect
	// hand edits, deletions, and stale copies. User-owned files (config.json,
	// local recipes) are deliberately not recorded.
	const generated = Object.create(null);
	const writeGenerated = (relPath, content) => {
		try {
			publishGeneratedFileSafely(targetDir, relPath, content);
		} catch (err) {
			fail(err.message);
		}
		generated[relPath] = sha256(content);
	};

	writeGenerated(
		".stdd/method.md",
		renderInstalledMethod(
			fs.readFileSync(path.join(PKG_ROOT, "method", "README.md"), "utf8"),
			existingConfig.projectLog.enabled,
		),
	);
	for (const pb of kitActive) {
		writeGenerated(
			`.stdd/playbooks/${pb.file}`,
			compile(pb, pb.source).replaceAll(CROSS_CLI_REVIEW_VIA_TOKEN, agentNeutralReviewVia),
		);
	}
	const configPath = path.join(stddDir, "config.json");
	if (!fs.existsSync(configPath)) {
		fs.writeFileSync(configPath, `${JSON.stringify(DEFAULT_CONFIG, null, "\t")}\n`);
	}
	console.log(`Installed .stdd/ (method, ${kitActive.length} playbooks, config)`);

	const managedInstructions = /<!-- stdd:begin[^>]*-->\r?\n[\s\S]*?<!-- stdd:end -->\r?\n?/;
	for (const tool of tools) {
		const adapter = getAgentAdapter(tool);
		for (const pb of [...kitActive, ...localActive]) {
			const skill = renderAgentSkill({
				adapter: tool,
				name: pb.meta.name,
				description: pb.meta.description,
				when: pb.meta.when,
				body: compile(pb, pb.body),
				stamp: STAMP,
			});
			writeGenerated(`${adapter.skillRoot}/${pb.meta.name}/SKILL.md`, skill);
		}
		const snippet = renderAgentInstructions({
			adapter: tool,
			stamp: STAMP,
			npmRunner: automationRunner,
			crossCli: capabilities.crossCli,
			projectLogEnabled: existingConfig.projectLog.enabled,
		});
		writeGenerated(adapter.snippetFile, snippet);
		const instructionsPath = resolveWritableRepoPath(
			targetDir,
			adapter.instructionsFile,
			`${adapter.instructionsFile} path`,
		);
		const block = `<!-- stdd:begin — managed section, re-run \`stdd init\` to update -->\n${snippet}<!-- stdd:end -->\n`;
		if (!fs.existsSync(instructionsPath)) {
			fs.mkdirSync(path.dirname(instructionsPath), { recursive: true });
			fs.writeFileSync(instructionsPath, block);
			console.log(`Wrote ${adapter.instructionsFile} with the managed STDD section`);
		} else {
			const current = fs.readFileSync(instructionsPath, "utf8");
			const updated = managedInstructions.test(current)
				? current.replace(managedInstructions, block)
				: `${current}${current.endsWith("\n") ? "" : "\n"}\n${block}`;
			if (updated !== current) fs.writeFileSync(instructionsPath, updated);
			console.log(`Updated the managed STDD section in ${adapter.instructionsFile}`);
		}
		console.log(
			`Installed ${kitActive.length + localActive.length} ${tool} skills under ${adapter.skillRoot}/`,
		);
	}
	for (const adapter of Object.values(AGENT_ADAPTERS).filter(
		(candidate) => !tools.includes(candidate.id),
	)) {
		const instructionsPath = resolveWritableRepoPath(
			targetDir,
			adapter.instructionsFile,
			`${adapter.instructionsFile} path`,
		);
		if (!fs.existsSync(instructionsPath)) continue;
		const current = fs.readFileSync(instructionsPath, "utf8");
		if (!managedInstructions.test(current)) continue;
		const updated = current.replace(managedInstructions, "");
		if (updated.trim() === "") fs.rmSync(instructionsPath);
		else fs.writeFileSync(instructionsPath, updated);
		console.log(`Removed the managed STDD section from deselected ${adapter.instructionsFile}`);
	}

	for (const provider of ci) {
		const adapter = CI_ADAPTERS[provider];
		if (adapter.outputFile === null) {
			console.log(
				`Portable CI contract for ${adapter.id} (compose with your provider's checkout and live PR/MR body):\n` +
					`  npx --yes @stdd/cli@${VERSION} check .\n` +
					`  printf '%s' "$REVIEW_BODY" | npx --yes @stdd/cli@${VERSION} check-pr - --base "$BASE_REF"`,
			);
			continue;
		}
		const workflow = renderCiTemplate(
			fs.readFileSync(path.join(PKG_ROOT, "templates", adapter.templateFile), "utf8"),
			{ stamp: STAMP, version: VERSION },
		);
		writeGenerated(adapter.outputFile, workflow);
		console.log(`Installed ${adapter.outputFile} (${provider} live review evidence)`);
	}

	if (hooks) {
		// One fast offline command only — network calls in hooks produce
		// false positives that train --no-verify. User-owned after
		// generation (like config.json): never manifested. A byte-for-byte
		// generated hook is safe to re-pin on upgrade; any user edit makes it
		// hands-off.
		const hookPath = resolveWritableRepoPath(targetDir, ".stdd/hooks/pre-push", "pre-push hook path");
		if (fs.existsSync(hookPath)) {
			const current = fs.readFileSync(hookPath, "utf8");
			const updated = prePushHook(automationRunner);
			if (current !== updated && isGeneratedPrePushHook(current)) {
				fs.writeFileSync(hookPath, updated, { mode: 0o755 });
				console.log("Re-pinned the generated .stdd/hooks/pre-push to this stdd version");
			} else {
				console.log(".stdd/hooks/pre-push already exists — left untouched (user-owned)");
			}
		} else {
			fs.mkdirSync(path.join(stddDir, "hooks"), { recursive: true });
			fs.writeFileSync(hookPath, prePushHook(automationRunner), {
				mode: 0o755,
			});
			console.log(
				"Installed .stdd/hooks/pre-push (runs stdd check — fast, offline). Wire it up with ONE of:\n" +
					"  git config core.hooksPath .stdd/hooks   # note: this disables hooks in .git/hooks\n" +
					"  …or call `stdd check` from your existing husky/lefthook pre-push",
			);
		}
	}

	if (sessionHook || stopHook) {
		installAgentHooks(targetDir, automationRunner, tools, {
			sessionHook,
			stopHook,
		});
	}
	if ((hooks || sessionHook || stopHook) && !hasLocalStddBinary(targetDir)) {
		console.error(
			"stdd init: automation was generated, but no project-local stdd binary is installed — " +
				"run `npm install --save-dev --save-exact @stdd/cli` before relying on hooks",
		);
	}

	// The ledger and the plan are per-checkout working artifacts — never
	// committed. The ignore rules are user-owned once written, not manifested.
	const gitignorePath = resolveWritableRepoPath(targetDir, ".gitignore", ".gitignore path");
	const gitignore = fs.existsSync(gitignorePath) ? fs.readFileSync(gitignorePath, "utf8") : "";
	const retainedLines = gitignore
		.split("\n")
		.filter((line) => line !== LEGACY_LEDGER_RESET_TEMP_IGNORE && line !== LEDGER_RESET_TEMP_GIT_GLOB);
	const retained = retainedLines.join("\n");
	const missing = [
		".stdd/ledger.jsonl",
		".stdd/plan.md",
		".stdd/worker.json",
		`${WORKER_DELETIONS_REL}/`,
	].filter((line) => !retainedLines.includes(line));
	if (retained !== gitignore || missing.length > 0) {
		const sep = retained === "" || retained.endsWith("\n") ? "" : "\n";
		fs.writeFileSync(
			gitignorePath,
			`${retained}${sep}${missing.join("\n")}${missing.length ? "\n" : ""}`,
		);
		if (missing.length > 0) {
			console.log(`Added ${missing.join(", ")} to .gitignore (per-checkout, never committed)`);
		}
	}

	// A profile or tool change may stop generating a file a previous init
	// wrote. Remove it only when still byte-identical to what init wrote —
	// a hand-edited file is never deleted. Cleanup precedes the replacement
	// manifest: on failure the previous manifest remains authoritative and
	// still accounts for every discoverable old output.
	const cleanupJournal = { version: 1, entries: [] };
	const manifestPublication = { renameAttempted: false, durable: false };
	try {
		for (const [file, hash] of Object.entries(oldFiles)) {
			if (Object.hasOwn(generated, file)) continue;
			const inspected = inspectManifestOutput(targetDir, file);
			if (inspected.kind === "missing") continue;
			if (inspected.kind === "invalid") {
				generated[file] = hash;
				console.error(
					`Preserved unsafe formerly generated output ${file}; it cannot be safely inspected (${inspected.reason}) and remains manifest-tracked until removed or relocated`,
				);
				continue;
			}
			if (
				MANIFEST_QUARANTINE_BASENAME.test(path.posix.basename(file)) &&
				sha256(inspected.bytes) === hash
			) {
				// A prior init already retired this output from its agent/CI load
				// path. Keep the identity-safe quarantine stable across re-init;
				// repeatedly renaming it would create churn without making a
				// pathname unlink any safer.
				generated[file] = hash;
				continue;
			}
			if (sha256(inspected.bytes) === hash) {
				if (process.platform !== "linux") {
					generated[file] = hash;
					console.error(
						`Preserved unsafe formerly generated output ${file}; atomic parent-bound cleanup is unavailable on this platform and it remains manifest-tracked until removed or relocated`,
					);
					continue;
				}
				const parentStat = fs.lstatSync(path.dirname(inspected.filePath));
				if (
					parentStat.isSymbolicLink() ||
					!parentStat.isDirectory() ||
					fs.realpathSync(path.dirname(inspected.filePath)) !== inspected.realParentPath
				) {
					generated[file] = hash;
					console.error(
						`Preserved unsafe formerly generated output ${file}; parent directory changed after inspection and it remains manifest-tracked until removed or relocated`,
					);
					continue;
				}
				const quarantineName = `.stdd-cleanup-${randomBytes(16).toString("hex")}.tmp`;
				const parent = path.posix.dirname(file);
				const quarantineFile = parent === "." ? quarantineName : `${parent}/${quarantineName}`;
				const entry = {
					source: file,
					quarantine: quarantineFile,
					hash,
					parentDev: String(parentStat.dev),
					parentIno: String(parentStat.ino),
					fileDev: String(inspected.identity.dev),
					fileIno: String(inspected.identity.ino),
					phase: "planned",
					keepSource: false,
					reason: "",
				};
				cleanupJournal.entries.push(entry);
				// This fsynced planned record is the write-ahead boundary: no
				// rename may happen unless recovery already knows both names and
				// both captured identities.
				writeCleanupJournal(targetDir, cleanupJournal);
				const removal = removeInspectedManifestOutput(inspected, hash, quarantineName);
				if (removal.unresolved) {
					entry.phase = "unresolved";
					entry.reason = removal.reason;
					try {
						writeCleanupJournal(targetDir, cleanupJournal);
					} catch {}
					throw new Error(removal.reason);
				}
				const state = inspectCleanupEntryState(targetDir, entry);
				if (removal.error) throw removal.error;
				if (!removal.removed) {
					if (state.kind !== "restored") {
						entry.phase = "unresolved";
						entry.reason =
							state.kind === "unresolved"
								? state.reason
								: "cleanup returned without a provably restored source";
						try {
							writeCleanupJournal(targetDir, cleanupJournal);
						} catch {}
						throw new Error(entry.reason);
					}
					cleanupJournal.entries.pop();
					if (cleanupJournal.entries.length > 0) writeCleanupJournal(targetDir, cleanupJournal);
					else clearCleanupJournal(targetDir);
					generated[file] = hash;
					console.error(
						`Preserved unsafe formerly generated output ${file}; ${removal.reason} and it remains manifest-tracked until removed or relocated`,
					);
					continue;
				}
				if (state.kind !== "quarantined") {
					entry.phase = "unresolved";
					entry.reason =
						state.kind === "unresolved"
							? state.reason
							: "cleanup did not leave the exact inode at its journaled quarantine";
					try {
						writeCleanupJournal(targetDir, cleanupJournal);
					} catch {}
					throw new Error(entry.reason);
				}
				entry.phase = "quarantined";
				entry.keepSource = state.keepSource;
				entry.reason = removal.warning ?? "";
				writeCleanupJournal(targetDir, cleanupJournal);
				generated[quarantineFile] = hash;
				if (state.keepSource) generated[file] = hash;
				if (removal.warning) console.error(`${file}: ${removal.warning}`);
				console.log(
					`Quarantined ${file} as ${quarantineFile} (no longer loaded by this profile; retained for identity-safe cleanup)`,
				);
			} else {
				// Preserve user edits, but never let a native agent keep loading an
				// unmanifested former output. Retaining the old expected hash makes
				// check/doctor report the file stale until its owner moves or removes it.
				generated[file] = hash;
				console.error(
					`Preserved modified formerly generated file ${file}; it remains manifest-tracked and stale until removed or relocated`,
				);
			}
		}

		// targets are remembered so `stdd configure` can recompile the same
		// outputs without re-asking what this repo generates. Publish last with a
		// same-directory atomic rename: a failed write never truncates the prior
		// manifest or authenticates only part of this generation.
		const manifest = {
			generatedBy: "stdd",
			version: VERSION,
			files: generated,
			targets: {
				tools,
				ci: rememberedCiTargets,
				hooks: rememberedHookTargets.hooks,
				sessionHook: rememberedHookTargets.sessionHook,
				stopHook: rememberedHookTargets.stopHook,
			},
		};
		publishManifestDurably(targetDir, manifest, manifestPublication);
		if (cleanupJournal.entries.length > 0) clearCleanupJournal(targetDir);
	} catch (err) {
		const unresolved = [];
		if (cleanupJournal.entries.length > 0) {
			const preexistingUnresolved = cleanupJournal.entries.filter(
				(entry) => entry.phase === "unresolved",
			);
			if (preexistingUnresolved.length > 0) {
				unresolved.push(
					...preexistingUnresolved.map(
						(entry) => `${entry.source}: ${entry.reason || "cleanup settlement is unresolved"}`,
					),
				);
				try {
					writeCleanupJournal(targetDir, cleanupJournal);
				} catch (journalError) {
					unresolved.push(`journal phase update: ${journalError.message}`);
				}
			} else if (manifestPublication.renameAttempted) {
				unresolved.push(
					"manifest publication crossed its rename boundary; the journal stays authoritative until next-init recovery",
				);
			} else {
				unresolved.push(...rollbackCleanupJournal(targetDir, cleanupJournal));
				if (unresolved.length === 0) {
					try {
						clearCleanupJournal(targetDir);
					} catch (clearError) {
						unresolved.push(`journal cleanup: ${clearError.message}`);
					}
				}
			}
		}
		if (unresolved.length > 0) {
			fail(`${err.message}; ${CLEANUP_JOURNAL_REL} remains for recovery — ${unresolved.join("; ")}`);
		}
		fail(err.message);
	}
}

/**
 * Shared repository scan for `check` and `doctor`: committed working
 * artifacts, canonical docs and their temporal-narrative hits, and stale
 * generated files (a stale stamp means the CLI was upgraded without
 * re-running `stdd init`).
 */
function scanRepo(targetDir, config) {
	const files = listTrackedFiles(targetDir);

	const projectLogForbidden = config.projectLog.enabled ? null : globToRegExp("docs/project/**");
	const projectLogArtifacts = projectLogForbidden
		? files.filter((file) => projectLogForbidden.test(file))
		: [];
	const projectLogArtifactSet = new Set(projectLogArtifacts);
	const forbidden = config.forbiddenArtifacts.map(globToRegExp);
	const artifacts = files.filter(
		(file) => !projectLogArtifactSet.has(file) && forbidden.some((re) => re.test(file)),
	);

	const canonical = config.canonicalDocs.map(globToRegExp);
	const canonicalFiles = files.filter((file) => canonical.some((re) => re.test(file)));
	const matchers = temporalMatchers(config.temporalPhrases);
	const temporal = [];
	for (const file of canonicalFiles) {
		const lines = fs.readFileSync(path.join(targetDir, file), "utf8").split("\n");
		for (const hit of scanTemporal(lines, matchers)) temporal.push({ file, ...hit });
	}

	const contentHits = [];
	let added = null;
	if (config.contentRules.some((r) => r.newFilesOnly)) {
		added = addedFiles(targetDir, config.baseRef);
	}
	for (const rule of config.contentRules) {
		const fileRe = globToRegExp(rule.files);
		let targets = files.filter((f) => fileRe.test(f));
		if (rule.newFilesOnly && added !== null) {
			targets = targets.filter((f) => added.includes(f));
		}
		for (const file of targets) {
			const content = fs.readFileSync(path.join(targetDir, file), "utf8");
			if (rule.forbid) {
				const re = new RegExp(rule.forbid);
				content.split("\n").forEach((line, i) => {
					if (re.test(line)) contentHits.push({ file, line: i + 1, rule });
				});
			}
			if (rule.require && !new RegExp(rule.require, "m").test(content)) {
				contentHits.push({ file, line: null, rule });
			}
		}
	}

	return {
		artifacts,
		projectLogArtifacts,
		bookkeeping: trackedBookkeeping(targetDir),
		canonicalFiles,
		temporal,
		contentHits,
		stale: scanGeneratedDrift(targetDir, config),
	};
}

/**
 * stdd's own per-checkout bookkeeping (the ledger, the plan) that git
 * tracks anyway. Hardcoded, not config-driven — these files are never
 * legitimate in history. Outside a git repo tracking is unknowable: [].
 */
function trackedBookkeeping(targetDir) {
	try {
		return execFileSync(
			"git",
			[
				"-C",
				targetDir,
				"ls-files",
				"--",
				".stdd/ledger.jsonl",
				".stdd/plan.md",
				".stdd/worker.json",
				`:(glob)${WORKER_DELETIONS_REL}/**`,
				...LEDGER_INTERNAL_TEMP_GIT_GLOBS.map((glob) => `:(glob)${glob}`),
			],
			{ encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] },
		)
			.split("\n")
			.filter(
				(file) =>
					file === ".stdd/ledger.jsonl" ||
					file === ".stdd/plan.md" ||
					file === WORKER_METADATA_REL ||
					file.startsWith(`${WORKER_DELETIONS_REL}/`) ||
					LEDGER_INTERNAL_TEMP_RELATIVE.test(file),
			);
	} catch {
		return [];
	}
}

/** Files added against baseRef, or null when the base is unresolvable. */
function addedFiles(targetDir, baseRef) {
	if (!baseRef) return null;
	try {
		return execFileSync(
			"git",
			[
				"-C",
				targetDir,
				"diff",
				"--diff-filter=A",
				"--name-only",
				"--end-of-options",
				`${baseRef}...HEAD`,
			],
			{ encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] },
		)
			.split("\n")
			.filter(Boolean);
	} catch {
		return null;
	}
}

/** Managed outputs that remain discoverable even when a partial init never
 * published its manifest, or an older buggy cleanup forgot one. */
function discoverGeneratedOutputs(targetDir) {
	const found = new Set();
	const addIfPresent = (relative) => {
		const candidate = path.join(targetDir, relative);
		try {
			fs.lstatSync(candidate);
			found.add(relative);
		} catch (err) {
			if (err.code !== "ENOENT") found.add(relative);
		}
	};

	addIfPresent(".stdd/method.md");
	for (const adapter of Object.values(AGENT_ADAPTERS)) addIfPresent(adapter.snippetFile);
	const shippedPlaybooks = loadPlaybooks();
	const reservedSkillNames = new Set([
		...shippedPlaybooks.map((playbook) => playbook.meta.name),
		...loadLocalPlaybooks(targetDir).map((playbook) => playbook.meta.name),
	]);
	for (const playbook of shippedPlaybooks) addIfPresent(`.stdd/playbooks/${playbook.file}`);
	for (const adapter of Object.values(CI_ADAPTERS)) {
		if (adapter.outputFile) addIfPresent(adapter.outputFile);
	}

	for (const adapter of Object.values(AGENT_ADAPTERS)) {
		// Shipped and validated local skill names reserve generated-output paths. Surface an
		// exact final object even when it cannot be opened as a stamped regular
		// file; absence remains normal, and unrelated user skill names are
		// still considered only when their contents carry the generated stamp.
		for (const name of reservedSkillNames) {
			addIfPresent(`${adapter.skillRoot}/${name}/SKILL.md`);
		}
		const skillsRoot = path.join(targetDir, adapter.skillRoot);
		let entries;
		try {
			entries = fs.readdirSync(skillsRoot, { withFileTypes: true });
		} catch (err) {
			if (err.code !== "ENOENT") found.add(adapter.skillRoot);
			continue;
		}
		for (const entry of entries) {
			if (!entry.isDirectory()) continue;
			const relative = `${adapter.skillRoot}/${entry.name}/SKILL.md`;
			const skillPath = path.join(targetDir, relative);
			try {
				if (
					fs.lstatSync(skillPath).isFile() &&
					/<!-- generated by stdd v[^\s]+ —/u.test(fs.readFileSync(skillPath, "utf8"))
				) {
					found.add(relative);
				}
			} catch {
				// A broken generated-looking skill path is still surfaced when
				// the manifest names it; unknown user-owned entries stay alone.
			}
		}
	}
	return [...found].sort();
}

/**
 * Generated-file drift, as `{ file, message }` findings. With a manifest
 * (written by `stdd init`), every generated file is verified by content
 * hash and managed outputs may not exist outside its inventory. Without a
 * manifest, any generated output is a failed or legacy partial install that
 * must be regenerated before it can be trusted.
 */
function scanGeneratedDrift(targetDir, config) {
	const stale = [];
	try {
		const cleanupJournal = readCleanupJournal(targetDir);
		if (cleanupJournal) {
			stale.push({
				file: CLEANUP_JOURNAL_REL,
				message:
					"pending generated-output cleanup transaction — run stdd init to recover or inspect its unresolved paths",
			});
		}
	} catch (err) {
		stale.push({
			file: CLEANUP_JOURNAL_REL,
			message: `invalid cleanup transaction journal (${err.message}) — inspect it before running stdd init`,
		});
	}
	let manifest;
	try {
		manifest = readManifestDocument(targetDir);
	} catch (err) {
		return [
			...stale,
			{
				file: ".stdd/manifest.json",
				message: `${err.message} — re-run stdd init`,
			},
		];
	}
	if (manifest) {
		let installedMethodBytes = null;
		if (manifest.version !== VERSION) {
			stale.push({
				file: ".stdd/manifest.json",
				message: `written by stdd v${manifest.version}, CLI is v${VERSION} — re-run stdd init`,
			});
		}
		for (const [file, hash] of Object.entries(manifest.files)) {
			const inspected = inspectManifestOutput(targetDir, file);
			if (inspected.kind === "missing") {
				stale.push({
					file,
					message: "listed in .stdd/manifest.json but missing — re-run stdd init",
				});
			} else if (inspected.kind === "invalid") {
				stale.push({
					file,
					message: `cannot be safely inspected as a readable regular file (${inspected.reason}) — remove it or re-run stdd init`,
				});
			} else {
				if (file === ".stdd/method.md") installedMethodBytes = inspected.bytes;
				if (sha256(inspected.bytes) === hash) continue;
				stale.push({
					file,
					message: "edited by hand or stale — re-run stdd init",
				});
			}
		}
		for (const file of discoverGeneratedOutputs(targetDir)) {
			if (!Object.hasOwn(manifest.files, file)) {
				stale.push({
					file,
					message:
						"looks generated by stdd but is not listed in .stdd/manifest.json — remove it or re-run stdd init",
				});
			}
		}
		if (installedMethodBytes !== null) {
			const canonicalMethod = Buffer.from(
				renderInstalledMethod(
					fs.readFileSync(path.join(PKG_ROOT, "method", "README.md"), "utf8"),
					config.projectLog.enabled,
				),
			);
			if (!installedMethodBytes.equals(canonicalMethod)) {
				stale.push({
					file: ".stdd/method.md",
					message: "does not match the canonical method shipped by this CLI — re-run stdd init",
				});
			}
		}
		const automationRunner = isStddSourceCheckout(targetDir) ? SOURCE_RUNNER : NPM_RUNNER;
		for (const tool of manifest.targets?.tools ?? []) {
			const adapter = getAgentAdapter(tool);
			const inspected = inspectManifestOutput(targetDir, adapter.snippetFile);
			if (inspected.kind !== "ok") continue;
			const expectedSnippet = Buffer.from(
				renderAgentInstructions({
					adapter,
					stamp: STAMP,
					npmRunner: automationRunner,
					crossCli: config.capabilities.crossCli,
					projectLogEnabled: config.projectLog.enabled,
				}),
			);
			if (
				!inspected.bytes.equals(expectedSnippet) &&
				!stale.some((finding) => finding.file === adapter.snippetFile)
			) {
				stale.push({
					file: adapter.snippetFile,
					message: "does not match the current repository policy — re-run stdd init",
				});
			}
		}
		return stale;
	}

	const partial = discoverGeneratedOutputs(targetDir);
	if (partial.length > 0) {
		for (const file of partial) {
			const inspected = inspectManifestOutput(targetDir, file);
			if (inspected.kind === "invalid") {
				stale.push({
					file,
					message: `unsafe object occupies an exact generated-output path (${inspected.reason}) — remove it or re-run stdd init`,
				});
			}
		}
		stale.push({
			file: ".stdd/manifest.json",
			message: `is missing for a partial install with generated output ${partial[0]} — re-run stdd init`,
		});
	}
	return stale;
}

function check(targetDir) {
	const config = loadConfig(targetDir);
	const { artifacts, projectLogArtifacts, bookkeeping, temporal, contentHits, stale } = scanRepo(
		targetDir,
		config,
	);
	const violations = [
		...artifacts.map((file) => `${file}: committed working artifact (forbiddenArtifacts)`),
		...projectLogArtifacts.map(
			(file) => `${file}: project log is disabled (projectLog.enabled is false)`,
		),
		...bookkeeping.map(
			(file) => `${file}: committed stdd working artifact — per-checkout only; add it to .gitignore`,
		),
		...temporal.map(
			(hit) => `${hit.file}:${hit.line}: temporal narrative in canonical doc ("${hit.phrase}")`,
		),
		...contentHits.map(
			(h) =>
				`${h.file}${h.line ? `:${h.line}` : ""}: ${h.rule.name}` +
				(h.rule.message ? ` — ${h.rule.message}` : h.line ? "" : " — required pattern not found"),
		),
		...stale.map((s) => `${s.file}: ${s.message}`),
	];
	// Enforced locally (the pre-push hook runs stdd check); a detached
	// checkout — CI — has no branch name to validate and skips the rule.
	if (config.branchPattern) {
		const branch = currentBranch(targetDir);
		if (branch && branch !== "HEAD" && !new RegExp(config.branchPattern).test(branch)) {
			violations.push(`branch "${branch}" does not match branchPattern ${config.branchPattern}`);
		}
	}

	if (violations.length > 0) {
		console.error(`stdd check: ${violations.length} violation(s)\n`);
		for (const v of violations) console.error(`  ${v}`);
		process.exit(1);
	}
	console.log("stdd check: OK");
}

/**
 * Config-declared worktree readiness: report each missing required path
 * with its repo-authored fix hint. Purely declarative — existence only,
 * nothing is executed or installed. Returns true when everything passes.
 */
function reportReadiness(targetDir, config, report) {
	const required = config.readiness.required;
	if (required.length === 0) return null;
	const missing = [];
	for (const entry of required) {
		let ready;
		try {
			ready = fs.existsSync(resolveRepoPath(targetDir, entry.path, `readiness path ${entry.path}`));
		} catch (err) {
			fail(`.stdd/config.json: ${err.message}`);
		}
		if (!ready) missing.push(entry);
	}
	for (const entry of missing) {
		report(false, `${entry.path} missing${entry.hint ? ` — ${entry.hint}` : ""}`);
	}
	if (missing.length === 0) {
		report(true, `worktree ready (${required.length}/${required.length} present)`);
	}
	return missing.length === 0;
}

function doctor(targetDir, readinessOnly = false) {
	const count = (n, singular, plural) => `${n} ${n === 1 ? singular : plural}`;
	let failed = false;
	const report = (ok, message) => {
		console.log(`${ok ? "✓" : "✗"} ${message}`);
		if (!ok) failed = true;
	};

	if (readinessOnly) {
		if (reportReadiness(targetDir, loadConfig(targetDir), report) === null) {
			console.log("no readiness contract declared (readiness.required in .stdd/config.json)");
		}
		if (failed) process.exit(1);
		return;
	}

	const installed = fs.existsSync(path.join(targetDir, ".stdd", "method.md"));
	report(installed, installed ? ".stdd/ installed" : ".stdd/ is not installed — run stdd init");

	const config = loadConfig(targetDir);
	reportReadiness(targetDir, config, report);
	const { artifacts, projectLogArtifacts, bookkeeping, canonicalFiles, temporal, contentHits, stale } =
		scanRepo(targetDir, config);

	if (config.contentRules.length > 0) {
		report(
			contentHits.length === 0,
			contentHits.length === 0
				? `content rules clean (${count(config.contentRules.length, "rule", "rules")})`
				: `${count(contentHits.length, "content-rule violation", "content-rule violations")} — see stdd check`,
		);
	}

	report(
		canonicalFiles.length > 0,
		canonicalFiles.length > 0
			? `canonical docs present (${count(canonicalFiles.length, "file", "files")})`
			: "no canonical docs found — create docs/domain/ or docs/product/, or adjust canonicalDocs",
	);

	if (projectLogArtifacts.length > 0) {
		report(
			false,
			`${count(projectLogArtifacts.length, "tracked project-log file", "tracked project-log files")} while projectLog.enabled is false — see stdd check`,
		);
	}
	const committed = artifacts.length + bookkeeping.length;
	report(
		committed === 0,
		committed === 0
			? projectLogArtifacts.length > 0
				? "no other committed working artifacts"
				: "no committed working artifacts"
			: `${count(committed, "committed working artifact", "committed working artifacts")} may mislead coding agents`,
	);

	const temporalFiles = new Set(temporal.map((hit) => hit.file)).size;
	report(
		temporalFiles === 0,
		temporalFiles === 0
			? "canonical docs match no configured temporal phrases"
			: `${count(temporalFiles, "canonical doc matches", "canonical docs match")} configured temporal phrases`,
	);

	for (const finding of stale.filter((entry) => entry.file === CLEANUP_JOURNAL_REL)) {
		report(false, `${finding.file}: ${finding.message}`);
	}
	report(
		stale.length === 0,
		stale.length === 0
			? `generated files match stdd v${VERSION}`
			: `${count(stale.length, "generated file is", "generated files are")} stale — re-run stdd init`,
	);

	// informational only — a missing hook is a choice, never a failure
	const hookInstalled = fs.existsSync(path.join(targetDir, ".stdd", "hooks", "pre-push"));
	console.log(
		hookInstalled
			? "· pre-push hook installed (.stdd/hooks/pre-push) — wire via git config core.hooksPath .stdd/hooks"
			: "· no pre-push hook installed — optional: stdd init --hooks",
	);
	let settingsText = "";
	for (const relative of new Set(Object.values(AGENT_ADAPTERS).map((adapter) => adapter.hooksFile))) {
		try {
			settingsText += fs.readFileSync(path.join(targetDir, relative), "utf8");
		} catch {
			// no settings for this agent
		}
	}
	if (
		hookInstalled ||
		/stdd (?:status|stop-hook)|STDD managed Pi lifecycle extension/.test(settingsText)
	) {
		console.log(
			hasLocalStddBinary(targetDir)
				? "· project-local stdd binary is available to hooks"
				: "· project-local stdd binary is missing — install exact @stdd/cli before relying on hooks",
		);
	}

	let selectedInstructionFiles = null;
	try {
		const manifest = readManifestDocument(targetDir);
		if (manifest && Object.hasOwn(manifest, "targets")) {
			const targets = manifest.targets;
			selectedInstructionFiles = new Set(
				targets.tools.map((tool) => getAgentAdapter(tool).instructionsFile),
			);
		}
	} catch (err) {
		const message = err.message.startsWith("targets ")
			? `.stdd/manifest.json targets are invalid — ${err.message.slice("targets ".length)}`
			: `.stdd/manifest.json is invalid — ${err.message}`;
		report(false, `${message}; re-run stdd init`);
		// Do not reinterpret corrupt target metadata as a legacy install.
		selectedInstructionFiles = new Set();
	}
	const instructionAdapters = new Map(
		Object.values(AGENT_ADAPTERS).map((adapter) => [adapter.instructionsFile, adapter]),
	);
	for (const [instructionsFile, adapter] of instructionAdapters) {
		if (selectedInstructionFiles && !selectedInstructionFiles.has(instructionsFile)) continue;
		const instructionsPath = path.join(targetDir, instructionsFile);
		if (!fs.existsSync(instructionsPath)) {
			if (selectedInstructionFiles) {
				report(false, `${instructionsFile} is missing — re-run stdd init for ${adapter.id}`);
			}
			continue;
		}
		const instructions = fs.readFileSync(instructionsPath, "utf8");
		const hasSection = [
			...instructions.matchAll(/<!-- stdd:begin(?:\s[^>]*)?-->\r?\n([\s\S]*?)<!-- stdd:end -->/gu),
		].some((match) => {
			const section = match[1];
			return (
				/^## STDD$/m.test(section) &&
				MANDATORY_ROUTING_SKILLS.every((name) =>
					section.includes(`\`${adapter.explicitPrefix}${name}\``),
				)
			);
		});
		report(
			hasSection,
			hasSection
				? `${instructionsFile} carries the STDD section`
				: `${instructionsFile} has no managed STDD routing contract — re-run stdd init for that agent`,
		);
	}

	const workflowsDir = path.join(targetDir, ".github", "workflows");
	if (fs.existsSync(workflowsDir)) {
		for (const file of fs.readdirSync(workflowsDir).filter((f) => /\.ya?ml$/.test(f))) {
			if (workflowValidatesStaleBody(fs.readFileSync(path.join(workflowsDir, file), "utf8"))) {
				report(
					false,
					`.github/workflows/${file} validates the frozen event payload body — ` +
						"body edits will not be re-checked; see stdd init --ci github",
				);
			}
		}
	}

	for (const rel of [
		"pull_request_template.md",
		".github/pull_request_template.md",
		"docs/pull_request_template.md",
	]) {
		const tplPath = path.join(targetDir, ...rel.split("/"));
		if (!fs.existsSync(tplPath)) continue;
		if (findEvidenceLines(fs.readFileSync(tplPath, "utf8")).length > 0) {
			report(
				false,
				`${rel} carries an unquoted evidence label — placeholder residue would pass ` +
					'the gate on every PR; quote template instructions ("> Docs …")',
			);
		}
	}

	if (failed) process.exit(1);
}

/**
 * With --pr: fetch the live PR (body, base, head) from the forge, so the
 * validation matches what CI will see — never a diverged local checkout.
 * Returns `{ body, baseRef, headRef, number }`.
 */
function resolveLivePr(pr) {
	const args = [
		"pr",
		"view",
		...(pr === "." ? [] : [pr]),
		"--json",
		"body,baseRefName,headRefOid,number",
	];
	let info;
	try {
		info = JSON.parse(
			execFileSync("gh", args, {
				encoding: "utf8",
				stdio: ["ignore", "pipe", "pipe"],
			}),
		);
	} catch (err) {
		if (err.code === "ENOENT") fail("--pr needs the GitHub CLI (gh) on PATH");
		fail(`gh pr view failed: ${err.stderr?.toString().trim().split("\n")[0] || err.message}`);
	}
	const baseRef = `origin/${info.baseRefName}`;
	try {
		git("fetch", "-q", "origin", info.baseRefName);
	} catch (err) {
		fail(
			`could not fetch origin/${info.baseRefName}: ${err.stderr?.toString().trim().split("\n")[0] || err.message}`,
		);
	}
	let headRef = "HEAD";
	if (git("rev-parse", "HEAD") !== info.headRefOid) {
		try {
			git("cat-file", "-e", `${info.headRefOid}^{commit}`);
		} catch {
			try {
				git("fetch", "-q", "origin", `pull/${info.number}/head`);
				git("cat-file", "-e", `${info.headRefOid}^{commit}`);
			} catch {
				fail(
					`local HEAD differs from PR head ${info.headRefOid.slice(0, 7)} and it could not ` +
						"be fetched — push or check out the PR branch",
				);
			}
		}
		headRef = info.headRefOid;
	}
	return { body: info.body, baseRef, headRef, number: info.number };
}

