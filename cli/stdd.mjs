function retirePortableTempMetadata(
	filePath,
	observed,
	{ preserve = false, prefix = ".stdd-remove" } = {},
) {
	let quarantine = null;
	try {
		const parent = path.dirname(filePath);
		const parentObserved = fs.lstatSync(parent);
		if (!parentObserved.isDirectory() || parentObserved.isSymbolicLink()) return false;
		const current = fs.lstatSync(filePath);
		if (!sameFileIdentity(current, observed)) return false;
		quarantine = path.join(parent, `${prefix}-${randomBytes(16).toString("hex")}.tmp`);
		fs.renameSync(filePath, quarantine);
		const parentAfter = fs.lstatSync(parent);
		const moved = fs.lstatSync(quarantine);
		if (!sameFileIdentity(parentObserved, parentAfter) || !sameFileIdentity(current, moved)) {
			if (!fs.existsSync(filePath)) fs.renameSync(quarantine, filePath);
			return false;
		}
		if (!preserve) {
			// Lock/owner files contain only STDD coordination metadata and
			// live in a sticky/private temp directory. The unpredictable
			// quarantine name narrows cleanup to the inode just moved out of
			// the authoritative lock path. Repository data uses preserve=true
			// because concurrent user edits must never be unlinked.
			try {
				fs.unlinkSync(quarantine);
			} catch {
				// The lock name is already retired. A cleanup remnant is inert
				// and preferable to making lock release fail after the action.
			}
		}
		quarantine = null;
		return true;
	} catch {
		return false;
	}
}

function lstatIfPresent(filePath) {
	try {
		return fs.lstatSync(filePath);
	} catch (err) {
		if (err.code === "ENOENT") return null;
		throw err;
	}
}

function retireHeldRepoTransactionTemp(
	heldDirectory,
	sourceName,
	observed,
	{ prefix = ".ledger-recovered" } = {},
) {
	const heldSource = path.join(heldDirectory.heldPath, sourceName);
	let quarantinePath = null;
	let moved = false;
	try {
		const parentOpened = fs.fstatSync(heldDirectory.descriptor);
		if (!sameFileIdentity(heldDirectory.identity, parentOpened)) {
			throw new Error("repository transaction parent changed after it was held");
		}
		const current = fs.lstatSync(heldSource);
		if (!sameFileIdentity(current, observed)) {
			throw new Error("repository transaction temp changed before retirement");
		}
		quarantinePath = path.join(
			heldDirectory.heldPath,
			`${prefix}-${randomBytes(16).toString("hex")}.tmp`,
		);
		fs.renameSync(heldSource, quarantinePath);
		moved = true;
		const movedObserved = fs.lstatSync(quarantinePath);
		const parentHeldAfter = fs.fstatSync(heldDirectory.descriptor);
		if (!sameFileIdentity(current, movedObserved) || !sameFileIdentity(parentOpened, parentHeldAfter)) {
			throw new Error("repository transaction temp changed during held-parent retirement");
		}
		const logicalParentAfter = fs.lstatSync(heldDirectory.logicalPath);
		if (
			logicalParentAfter.isSymbolicLink() ||
			!logicalParentAfter.isDirectory() ||
			!sameFileIdentity(parentOpened, logicalParentAfter)
		) {
			// The rename was still confined to the held directory. Restore the
			// non-authoritative temp only when its old name is still absent.
			const sourceAfter = lstatIfPresent(heldSource);
			const quarantineAfter = lstatIfPresent(quarantinePath);
			if (sourceAfter === null && quarantineAfter && sameFileIdentity(current, quarantineAfter)) {
				fs.renameSync(quarantinePath, heldSource);
				const restored = fs.lstatSync(heldSource);
				if (!sameFileIdentity(current, restored)) {
					throw new Error("repository transaction temp changed while restoring held evidence");
				}
				quarantinePath = null;
				moved = false;
			}
			throw new Error(
				"repository transaction parent changed during held-parent retirement; no outside path was modified",
			);
		}
		quarantinePath = null;
		return { retired: true };
	} catch (err) {
		if (moved && quarantinePath !== null) {
			try {
				const sourceAfter = lstatIfPresent(heldSource);
				const quarantineAfter = lstatIfPresent(quarantinePath);
				if (
					sourceAfter === null &&
					quarantineAfter &&
					sameFileIdentity(observed, quarantineAfter) &&
					sameFileIdentity(heldDirectory.identity, fs.fstatSync(heldDirectory.descriptor))
				) {
					fs.renameSync(quarantinePath, heldSource);
				}
			} catch {}
		}
		return {
			retired: false,
			reason: `${err.message}; the repository transaction temp was preserved for inspection`,
		};
	}
}

function retireRepoTransactionTemp(filePath, observed, options = {}) {
	if (process.platform !== "linux") {
		return {
			retired: false,
			reason:
				"safe repository transaction-temp retirement needs Linux held-parent support; the file was preserved",
		};
	}
	let heldDirectory = null;
	try {
		heldDirectory = openHeldLinuxRepoDirectory(
			path.dirname(path.dirname(filePath)),
			".stdd",
			"repository transaction parent",
		);
		return retireHeldRepoTransactionTemp(heldDirectory, path.basename(filePath), observed, options);
	} catch (err) {
		return {
			retired: false,
			reason: `${err.message}; the repository transaction temp was preserved for inspection`,
		};
	} finally {
		if (heldDirectory !== null) {
			try {
				fs.closeSync(heldDirectory.descriptor);
			} catch {}
		}
	}
}

function recoverAbandonedLedgerLock(lockPath) {
	let observed;
	let owner = null;
	try {
		observed = fs.lstatSync(lockPath);
		if (!observed.isFile() || observed.isSymbolicLink()) return false;
		try {
			owner = JSON.parse(fs.readFileSync(lockPath, "utf8"));
		} catch {
			// Legacy lock acquisition exposed this inode before writing owner
			// metadata. A grace period protects a live, just-created lock.
		}
	} catch {
		return false;
	}
	const validOwner =
		Number.isSafeInteger(owner?.pid) &&
		owner.pid > 0 &&
		typeof owner.token === "string" &&
		/^[0-9a-f]{32}$/.test(owner.token);
	if (!validOwner) {
		const age = Date.now() - Math.max(observed.mtimeMs, observed.ctimeMs);
		return age >= LEDGER_PARTIAL_LOCK_GRACE_MS ? retirePortableTempMetadata(lockPath, observed) : false;
	}
	try {
		process.kill(owner.pid, 0);
		return false;
	} catch (err) {
		if (err.code !== "ESRCH") return false;
	}
	const recovered = retirePortableTempMetadata(lockPath, observed);
	if (recovered) {
		const ownerPath = `${lockPath}.${owner.pid}.${owner.token}.owner`;
		retirePortableTempMetadata(ownerPath, observed);
	}
	return recovered;
}

/**
 * Remove only transaction temps that this CLI could have created. Recovery
 * runs after acquiring the ledger lock, so no live reset can own a matching
 * file. Anything with the internal name but without the exact private-file
 * shape is left untouched and blocks ledger mutation for manual inspection.
 */
function recoverLedgerResetTemps(cwd) {
	const ledgerPath = statePath(cwd, LEDGER_REL, "ledger path");
	const ledgerDir = path.dirname(ledgerPath);
	if (!fs.existsSync(ledgerDir)) return;
	const currentUid = typeof process.getuid === "function" ? process.getuid() : null;
	let heldDirectory = null;
	let recoveryDir = ledgerDir;
	let activeNames;
	if (process.platform === "linux") {
		try {
			heldDirectory = openHeldLinuxRepoDirectory(cwd, ".stdd", "repository transaction parent");
		} catch (err) {
			if (!err.stddHeldNamespaceUnavailable) throw err;
			const names = fs.readdirSync(ledgerDir).filter((name) => LEDGER_ACTIVE_TEMP_BASENAME.test(name));
			if (names.length === 0) return;
			throw new Error(
				`${err.message}; safe ledger transaction recovery requires a held repository namespace, so every temp was preserved`,
			);
		}
		recoveryDir = heldDirectory.heldPath;
	}
	try {
		activeNames = fs
			.readdirSync(recoveryDir)
			.filter((candidate) => LEDGER_ACTIVE_TEMP_BASENAME.test(candidate))
			.sort();
		for (const name of activeNames) {
			const relative = `.stdd/${name}`;
			const tempPath = path.join(recoveryDir, name);
			let observed;
			try {
				observed = fs.lstatSync(tempPath);
			} catch (err) {
				if (err.code === "ENOENT") continue;
				throw err;
			}
			const safe =
				observed.isFile() &&
				!observed.isSymbolicLink() &&
				observed.nlink === 1 &&
				(observed.mode & 0o777) === 0o600 &&
				(currentUid === null || observed.uid === currentUid);
			if (!safe) {
				throw new Error(
					`unsafe ledger transaction temporary file ${JSON.stringify(relative)} — ` +
						"expected a regular owner-only (0600) file owned by the current user; remove it manually",
				);
			}
			const retirement =
				heldDirectory === null
					? retireRepoTransactionTemp(tempPath, observed, { prefix: ".ledger-recovered" })
					: retireHeldRepoTransactionTemp(heldDirectory, name, observed, {
							prefix: ".ledger-recovered",
						});
			if (!retirement.retired) {
				throw new Error(
					`ledger transaction temporary file ${JSON.stringify(relative)} changed during recovery; ` +
						`nothing recorded — ${retirement.reason}`,
				);
			}
		}
	} finally {
		if (heldDirectory !== null) {
			try {
				fs.closeSync(heldDirectory.descriptor);
			} catch {}
		}
	}
}

function withLedgerLock(cwd, action) {
	const lockPath = ledgerLockPath(cwd);
	const token = randomBytes(16).toString("hex");
	const ownerPath = `${lockPath}.${process.pid}.${token}.owner`;
	const deadline = Date.now() + 10_000;
	let ownerFd;
	let ownerStat;
	let lockStat;
	try {
		ownerFd = fs.openSync(ownerPath, "wx", 0o600);
		ownerStat = fs.fstatSync(ownerFd);
		fs.writeFileSync(
			ownerFd,
			JSON.stringify({
				pid: process.pid,
				token,
				createdAt: new Date().toISOString(),
			}),
		);
		fs.fsyncSync(ownerFd);
		fs.closeSync(ownerFd);
		ownerFd = null;
	} catch (err) {
		if (ownerFd !== null && ownerFd !== undefined) {
			try {
				fs.closeSync(ownerFd);
			} catch {
				// The unique owner path is removed below.
			}
		}
		if (ownerStat && !retirePortableTempMetadata(ownerPath, ownerStat)) {
			throw new Error(
				`${err.message}; additionally, could not retire the private ledger lock owner file at ${ownerPath}`,
				{ cause: err },
			);
		}
		throw err;
	}
	let result;
	let actionFailure = null;
	try {
		for (;;) {
			try {
				// The shared name appears atomically only after complete owner
				// metadata has been written and flushed to its inode.
				fs.linkSync(ownerPath, lockPath);
				lockStat = ownerStat;
				if (!retirePortableTempMetadata(ownerPath, ownerStat)) {
					const lockRetired = retirePortableTempMetadata(lockPath, lockStat);
					if (lockRetired) lockStat = null;
					throw new Error(
						lockRetired
							? "could not retire the private ledger lock owner file"
							: "could not retire the private ledger lock owner file or release the shared lock",
					);
				}
				ownerStat = null;
				break;
			} catch (err) {
				if (err.code !== "EEXIST") throw err;
				if (recoverAbandonedLedgerLock(lockPath)) continue;
				if (Date.now() >= deadline) {
					throw new Error("the ledger is busy in another stdd process; retry the command");
				}
				Atomics.wait(LEDGER_LOCK_WAIT, 0, 0, 20);
			}
		}
		recoverLedgerResetTemps(cwd);
		result = action();
	} catch (err) {
		actionFailure = err;
	}
	const releaseFailures = [];
	if (lockStat && !retirePortableTempMetadata(lockPath, lockStat)) {
		releaseFailures.push("shared lock");
	}
	if (ownerStat && !retirePortableTempMetadata(ownerPath, ownerStat)) {
		releaseFailures.push("owner file");
	}
	if (releaseFailures.length > 0) {
		const releaseMessage = `could not release the ledger ${releaseFailures.join(
			" and ",
		)} safely; inspect ${lockPath}`;
		throw new Error(
			actionFailure ? `${actionFailure.message}; additionally, ${releaseMessage}` : releaseMessage,
			actionFailure ? { cause: actionFailure } : undefined,
		);
	}
	if (actionFailure) throw actionFailure;
	return result;
}

function jsonlRecordSeparator(byteLength, finalByte) {
	return byteLength > 0 && finalByte !== LF_BYTE ? "\n" : "";
}

function ledgerFileRecordSeparator(ledgerPath) {
	let fd;
	try {
		fd = fs.openSync(ledgerPath, "r");
	} catch (err) {
		if (err.code === "ENOENT") return "";
		throw err;
	}
	try {
		const size = fs.fstatSync(fd).size;
		if (size === 0) return "";
		const finalByte = Buffer.allocUnsafe(1);
		if (fs.readSync(fd, finalByte, 0, 1, size - 1) !== 1) {
			throw new Error("could not read the final ledger byte before appending");
		}
		return jsonlRecordSeparator(size, finalByte[0]);
	} finally {
		fs.closeSync(fd);
	}
}

function appendLedger(
	cwd,
	event,
	{
		allowHistoricalTask = false,
		allowBranchScopedHistorical = false,
		preserveTaskScope = false,
		lockHeld = false,
		expectedBranch = null,
	} = {},
) {
	const ledgerPath = statePath(cwd, LEDGER_REL, "ledger path");
	fs.mkdirSync(path.dirname(ledgerPath), { recursive: true });
	const write = () => {
		const { branch, taskState, task } = inspectLedgerAppendContext(cwd, event, {
			allowHistoricalTask,
			allowBranchScopedHistorical,
		});
		if (expectedBranch !== null && branch !== expectedBranch) {
			throw new Error(
				`the checkout switched branches before ${event.event} was recorded — nothing recorded; ` +
					`retry on ${expectedBranch}`,
			);
		}
		const recordedBranch = expectedBranch ?? branch;
		if (taskState.state === "legacy" && event.event !== "task-start") {
			console.error(
				'stdd: no active task; recording branch-scoped legacy evidence — run `stdd task start "<short name>"`',
			);
		}
		const separator = ledgerFileRecordSeparator(ledgerPath);
		fs.appendFileSync(
			ledgerPath,
			`${separator}${JSON.stringify({
				ts: new Date().toISOString(),
				...(task && !event.taskId && !preserveTaskScope ? { taskId: task.id } : {}),
				...event,
				...(taskState.state === "legacy" && LEGACY_RECORDER_EVENTS.has(event.event)
					? { legacyFlow: LEGACY_FLOW_MARKER }
					: {}),
				branch: recordedBranch,
			})}\n`,
		);
	};
	try {
		if (lockHeld) write();
		else withLedgerLock(cwd, write);
	} catch (err) {
		if (lockHeld) throw err;
		fail(err.message);
	}
}

function writeAllSync(fd, data) {
	const buffer = Buffer.isBuffer(data) ? data : Buffer.from(data);
	let offset = 0;
	while (offset < buffer.length) {
		const written = fs.writeSync(fd, buffer, offset, buffer.length - offset, null);
		if (written <= 0) throw new Error("could not complete the ledger transaction write");
		offset += written;
	}
}

/**
 * Publish adjacent ledger records as one copy-on-write transaction. The caller
 * holds the ledger lock and prepares every fallible input before entering. A
 * failed/partial temp write or process interruption leaves ledger.jsonl
 * untouched; rename is the only commit point.
 */
function readHeldLedger(heldDirectory) {
	const heldLedger = path.join(heldDirectory.heldPath, "ledger.jsonl");
	let descriptor = null;
	try {
		descriptor = fs.openSync(heldLedger, fs.constants.O_RDONLY | fs.constants.O_NOFOLLOW);
	} catch (err) {
		if (err.code === "ENOENT") {
			return { existed: false, content: Buffer.alloc(0), mode: 0o600, identity: null };
		}
		throw err;
	}
	try {
		const opened = fs.fstatSync(descriptor);
		const named = fs.lstatSync(heldLedger);
		const parent = fs.fstatSync(heldDirectory.descriptor);
		if (
			opened.isSymbolicLink() ||
			!opened.isFile() ||
			named.isSymbolicLink() ||
			!named.isFile() ||
			!sameFileIdentity(opened, named) ||
			!sameFileIdentity(heldDirectory.identity, parent)
		) {
			throw new Error("ledger changed while it was opened through the captured ledger parent");
		}
		const content = fs.readFileSync(descriptor);
		const afterRead = fs.fstatSync(descriptor);
		const afterNamed = fs.lstatSync(heldLedger);
		if (
			!samePublicationObservation(opened, afterRead) ||
			!samePublicationObservation(afterRead, afterNamed)
		) {
			throw new Error("ledger changed while its transaction snapshot was read");
		}
		return {
			existed: true,
			content,
			mode: opened.mode & 0o777,
			identity: afterRead,
		};
	} finally {
		fs.closeSync(descriptor);
	}
}

function validateHeldLedgerCommit(
	heldDirectory,
	ledgerPath,
	tempDescriptor,
	tempIdentity,
	{ bindDescriptor = true } = {},
) {
	const heldLedger = path.join(heldDirectory.heldPath, "ledger.jsonl");
	const heldPublished = fs.lstatSync(heldLedger);
	const published = bindDescriptor ? fs.fstatSync(tempDescriptor) : heldPublished;
	const heldParent = fs.fstatSync(heldDirectory.descriptor);
	if (
		published.isSymbolicLink() ||
		!published.isFile() ||
		heldPublished.isSymbolicLink() ||
		!heldPublished.isFile() ||
		!samePublicationPayload(tempIdentity, published) ||
		!samePublicationObservation(published, heldPublished) ||
		!sameFileIdentity(heldDirectory.identity, heldParent)
	) {
		throw new Error("ledger transaction temporary file was replaced at commit");
	}
	const logicalParent = fs.lstatSync(heldDirectory.logicalPath);
	const logicalPublished = fs.lstatSync(ledgerPath);
	if (
		logicalParent.isSymbolicLink() ||
		!logicalParent.isDirectory() ||
		!sameFileIdentity(heldDirectory.identity, logicalParent) ||
		!samePublicationObservation(heldPublished, logicalPublished)
	) {
		throw new Error(
			"ledger directory changed during commit; the final rename stayed inside the captured ledger parent",
		);
	}
	return heldPublished;
}

function validateHeldOriginalLedger(heldDirectory, originalLedger) {
	const heldLedger = path.join(heldDirectory.heldPath, "ledger.jsonl");
	const current = lstatIfPresent(heldLedger);
	const unchanged = originalLedger.existed
		? current !== null &&
			!current.isSymbolicLink() &&
			current.isFile() &&
			samePublicationObservation(originalLedger.identity, current)
		: current === null;
	if (!unchanged || !sameFileIdentity(heldDirectory.identity, fs.fstatSync(heldDirectory.descriptor))) {
		throw new Error(
			"ledger changed after its transaction snapshot; the prepared reset was not committed",
		);
	}
}

function restoreHeldLedgerAfterRejectedCommit(
	heldDirectory,
	tempIdentity,
	original,
	originalMode,
	ledgerExisted,
) {
	const heldLedger = path.join(heldDirectory.heldPath, "ledger.jsonl");
	const rejectedPath = path.join(
		heldDirectory.heldPath,
		`.ledger-rejected-${randomBytes(16).toString("hex")}.tmp`,
	);
	let restoreDescriptor = null;
	let restorePath = null;
	try {
		const current = fs.lstatSync(heldLedger);
		if (!samePublicationObservation(tempIdentity, current)) {
			throw new Error("committed transaction inode changed before held-parent settlement");
		}
		let restoreIdentity = null;
		if (ledgerExisted) {
			restorePath = path.join(
				heldDirectory.heldPath,
				`.ledger-aborted-${randomBytes(16).toString("hex")}.tmp`,
			);
			restoreDescriptor = fs.openSync(restorePath, "wx", 0o600);
			fs.fchmodSync(restoreDescriptor, originalMode);
			writeAllSync(restoreDescriptor, original);
			fs.fsyncSync(restoreDescriptor);
			restoreIdentity = fs.fstatSync(restoreDescriptor);
			const restoreNamed = fs.lstatSync(restorePath);
			if (!samePublicationObservation(restoreIdentity, restoreNamed)) {
				throw new Error("ledger restoration temp changed before held-parent settlement");
			}
		}
		fs.renameSync(heldLedger, rejectedPath);
		const rejected = fs.lstatSync(rejectedPath);
		if (!samePublicationPayload(tempIdentity, rejected)) {
			throw new Error("rejected ledger changed during held-parent settlement");
		}
		if (ledgerExisted) {
			fs.renameSync(restorePath, heldLedger);
			restorePath = null;
			const restored = fs.lstatSync(heldLedger);
			if (!samePublicationPayload(restoreIdentity, restored)) {
				throw new Error("original ledger changed during held-parent restoration");
			}
		}
		fs.fsyncSync(heldDirectory.descriptor);
		return { settled: true };
	} catch (err) {
		return {
			settled: false,
			reason: `${err.message}; held-parent evidence was preserved for inspection`,
		};
	} finally {
		if (restoreDescriptor !== null) {
			try {
				fs.closeSync(restoreDescriptor);
			} catch {}
		}
	}
}

function appendLedgerTransactionHeld(cwd, events, expectedBranch, heldDirectory) {
	const ledgerPath = statePath(cwd, LEDGER_REL, "ledger path");
	const assertBranch = () => {
		if (currentBranch(cwd) !== expectedBranch) {
			throw new Error(
				`the checkout switched branches before the task reset was recorded — nothing recorded; ` +
					`retry on ${expectedBranch}`,
			);
		}
	};
	assertBranch();

	const originalLedger = readHeldLedger(heldDirectory);
	const original = originalLedger.content;
	const separator = jsonlRecordSeparator(original.length, original.at(-1));
	const transaction = events.map(
		(event) =>
			`${JSON.stringify({
				ts: new Date().toISOString(),
				...event,
				branch: expectedBranch,
			})}\n`,
	);
	const tempName = `.ledger-reset-${randomBytes(16).toString("hex")}.tmp`;
	const preparedName = `.ledger-prepared-${randomBytes(16).toString("hex")}.tmp`;
	const heldTemp = path.join(heldDirectory.heldPath, tempName);
	const heldPrepared = path.join(heldDirectory.heldPath, preparedName);
	const heldLedger = path.join(heldDirectory.heldPath, "ledger.jsonl");
	let descriptor = null;
	let tempIdentity = null;
	let activeName = tempName;
	let finalRenameCompleted = false;
	let committed = false;
	let transactionFailure = null;
	let settlementFailure = null;
	try {
		descriptor = fs.openSync(heldTemp, "wx", 0o600);
		writeAllSync(descriptor, original);
		writeAllSync(descriptor, separator);
		for (const record of transaction) writeAllSync(descriptor, record);
		fs.fsyncSync(descriptor);
		tempIdentity = fs.fstatSync(descriptor);
		assertBranch();
		const beforeRename = fs.lstatSync(heldTemp);
		const parentBeforeRename = fs.fstatSync(heldDirectory.descriptor);
		if (
			beforeRename.isSymbolicLink() ||
			!beforeRename.isFile() ||
			!samePublicationObservation(tempIdentity, beforeRename) ||
			!sameFileIdentity(heldDirectory.identity, parentBeforeRename)
		) {
			throw new Error("ledger transaction temporary file changed before commit");
		}
		fs.renameSync(heldTemp, heldPrepared);
		activeName = preparedName;
		const prepared = fs.lstatSync(heldPrepared);
		const preparedDescriptor = fs.fstatSync(descriptor);
		if (
			prepared.isSymbolicLink() ||
			!prepared.isFile() ||
			!samePublicationPayload(tempIdentity, preparedDescriptor) ||
			!samePublicationObservation(preparedDescriptor, prepared)
		) {
			throw new Error("ledger transaction temporary file was replaced before commit");
		}
		tempIdentity = preparedDescriptor;
		assertBranch();
		validateHeldOriginalLedger(heldDirectory, originalLedger);
		fs.renameSync(heldPrepared, heldLedger);
		activeName = "ledger.jsonl";
		finalRenameCompleted = true;
		fs.fsyncSync(heldDirectory.descriptor);
		const committedDescriptor = fs.fstatSync(descriptor);
		if (!samePublicationPayload(tempIdentity, committedDescriptor)) {
			throw new Error("ledger transaction temporary file was replaced at commit");
		}
		tempIdentity = committedDescriptor;
		validateHeldLedgerCommit(heldDirectory, ledgerPath, descriptor, tempIdentity);
		fs.closeSync(descriptor);
		descriptor = null;
		validateHeldLedgerCommit(heldDirectory, ledgerPath, null, tempIdentity, {
			bindDescriptor: false,
		});
		committed = true;
	} catch (err) {
		transactionFailure = err;
	} finally {
		if (descriptor !== null) {
			try {
				if (tempIdentity !== null) {
					const named =
						activeName === "ledger.jsonl"
							? lstatIfPresent(heldLedger)
							: lstatIfPresent(path.join(heldDirectory.heldPath, activeName));
					if (named && sameFileIdentity(tempIdentity, named)) fs.fstatSync(descriptor);
				}
				fs.closeSync(descriptor);
			} catch {}
		}
		if (!committed && tempIdentity !== null) {
			if (finalRenameCompleted) {
				const settlement = restoreHeldLedgerAfterRejectedCommit(
					heldDirectory,
					tempIdentity,
					original,
					originalLedger.mode,
					originalLedger.existed,
				);
				if (!settlement.settled) settlementFailure = settlement.reason;
			} else {
				const retirement = retireHeldRepoTransactionTemp(heldDirectory, activeName, tempIdentity, {
					prefix: ".ledger-aborted",
				});
				if (!retirement.retired) settlementFailure = retirement.reason;
			}
		}
	}
	if (settlementFailure) {
		throw new Error(
			`${transactionFailure?.message ?? "ledger transaction failed"}; ` +
				`could not safely retire failed ledger transaction temp or settle its held commit — ` +
				settlementFailure,
		);
	}
	if (transactionFailure) throw transactionFailure;
	return validateHeldLedgerCommit(heldDirectory, ledgerPath, null, tempIdentity, {
		bindDescriptor: false,
	});
}

function appendLedgerTransaction(cwd, events, expectedBranch) {
	if (process.platform !== "linux") {
		throw new Error(
			"task reset requires Linux held-parent support; nothing recorded and no transaction temp was created",
		);
	}
	const ledgerPath = statePath(cwd, LEDGER_REL, "ledger path");
	const ledgerDir = path.dirname(ledgerPath);
	fs.mkdirSync(ledgerDir, { recursive: true });
	let heldDirectory;
	try {
		heldDirectory = openHeldLinuxRepoDirectory(cwd, ".stdd", "ledger directory");
	} catch (err) {
		if (err.stddHeldNamespaceUnavailable) {
			throw new Error(
				`${err.message}; task reset requires a held repository namespace, so nothing was recorded and no transaction temp was created`,
			);
		}
		throw err;
	}
	let committedIdentity = null;
	let transactionFailure = null;
	try {
		committedIdentity = appendLedgerTransactionHeld(cwd, events, expectedBranch, heldDirectory);
	} catch (err) {
		transactionFailure = err;
	}
	const parentBeforeClose = fs.fstatSync(heldDirectory.descriptor);
	if (!sameFileIdentity(heldDirectory.identity, parentBeforeClose) && transactionFailure === null) {
		transactionFailure = new Error("captured ledger parent changed before descriptor close");
	}
	fs.closeSync(heldDirectory.descriptor);
	if (transactionFailure) throw transactionFailure;
	const logicalParentAfterClose = fs.lstatSync(heldDirectory.logicalPath);
	const logicalLedgerAfterClose = fs.lstatSync(ledgerPath);
	if (
		logicalParentAfterClose.isSymbolicLink() ||
		!logicalParentAfterClose.isDirectory() ||
		!sameFileIdentity(heldDirectory.identity, logicalParentAfterClose) ||
		!samePublicationObservation(committedIdentity, logicalLedgerAfterClose)
	) {
		throw new Error(
			"ledger directory changed around captured-parent descriptor close; commit evidence was preserved",
		);
	}
}

/** Current task's ledger events. Branch-only history remains a legacy scope. */
function loadLedger(cwd, branch, config = loadConfig(cwd)) {
	return scopeLedgerForCheckout(cwd, branch, rawLedger(cwd, branch), config).events;
}

function planHash(cwd) {
	const planPath = statePath(cwd, PLAN_REL, "plan path");
	return fs.existsSync(planPath) ? sha256(fs.readFileSync(planPath)) : null;
}

function taskPlanContent(cwd, taskState, planPath = statePath(cwd, PLAN_REL, "plan path")) {
	if (!fs.existsSync(planPath) || taskState.state === "idle" || taskState.state === "invalid") {
		return null;
	}
	const content = fs.readFileSync(planPath, "utf8");
	if (
		taskState.state === "active" &&
		taskState.task.planBaseline !== null &&
		taskState.task.planBaseline === sha256(content)
	) {
		return null;
	}
	return content;
}

/**
 * Return the plan that belongs to the current task. A plan left unchanged
 * across `task start` is historical context, not the new task's contract.
 * Branch-only ledgers retain their legacy behavior.
 */
function currentTaskPlan(cwd) {
	const planPath = statePath(cwd, PLAN_REL, "plan path");
	if (!fs.existsSync(planPath)) return null;
	const branch = currentBranch(cwd);
	if (!branch) return fs.readFileSync(planPath, "utf8");
	const taskState = scopeLedgerForCheckout(cwd, branch).state;
	return taskPlanContent(cwd, taskState, planPath);
}

function normalizeTaskName(name) {
	try {
		return assertPrintableSingleLine(name, "task name").trim();
	} catch {
		if (typeof name !== "string" || name.trim() === "") {
			fail('task start needs a short name, e.g. `stdd task start "add invoices"`');
		}
		fail("task name must be a non-empty single printable line without control characters");
	}
}

function taskTransition(cwd, action) {
	try {
		return withLedgerLock(cwd, () => {
			const branch = currentBranch(cwd);
			if (!branch) {
				throw new Error("the ledger needs a git repository with at least one commit");
			}
			return action(branch);
		});
	} catch (err) {
		fail(err.message);
	}
}

function startTask(cwd, name) {
	const taskName = normalizeTaskName(name);
	const started = taskTransition(cwd, (branch) => {
		const taskState = taskLifecycleState(rawLedger(cwd, branch));
		if (taskState.state === "active") {
			throw new Error(
				`task ${taskState.task.id} (${taskState.task.name}) is already active — ` +
					"finish it, reset it, or continue it",
			);
		}
		const id = `task-${randomBytes(6).toString("hex")}`;
		appendLedger(
			cwd,
			{
				event: "task-start",
				id,
				name: taskName,
				planBaseline: planHash(cwd),
			},
			{ lockHeld: true, expectedBranch: branch },
		);
		return { branch, id };
	});
	console.log(`stdd task: started ${started.id} (${taskName}) on ${started.branch}`);
}

function finishTask(cwd) {
	const active = taskTransition(cwd, (branch) => {
		const taskState = taskLifecycleState(rawLedger(cwd, branch));
		if (taskState.state !== "active") {
			throw new Error('no active task — run `stdd task start "<name>"`');
		}
		const task = taskState.task;
		appendLedger(
			cwd,
			{ event: "task-finish", taskId: task.id },
			{ lockHeld: true, expectedBranch: branch },
		);
		return task;
	});
	console.log(`stdd task: finished ${active.id} (${active.name}); evidence remains in the ledger`);
}

function resetTask(cwd, name = null) {
	const requestedName = name === null ? null : normalizeTaskName(name);
	const reset = taskTransition(cwd, (branch) => {
		const taskState = taskLifecycleState(rawLedger(cwd, branch));
		if (taskState.state !== "active") {
			throw new Error('no active task — run `stdd task start "<name>"`');
		}
		const active = taskState.task;
		const nextName = requestedName ?? active.name;
		const id = `task-${randomBytes(6).toString("hex")}`;
		const planBaseline = planHash(cwd);
		appendLedgerTransaction(
			cwd,
			[
				{ event: "task-reset", taskId: active.id },
				{
					event: "task-start",
					id,
					name: nextName,
					planBaseline,
				},
			],
			branch,
		);
		return { branch, id, nextName };
	});
	console.log(`stdd task: reset to ${reset.id} (${reset.nextName}) on ${reset.branch}`);
}

/** `stdd docs <decision> [paths…] [--reason <why>]` — record the docs decision. */
function recordDocs(cwd, decision, paths, reason) {
	if (!DOCS_DECISIONS.includes(decision)) {
		// Free text is the recurring mistake — answer with the exact forms
		// and, when a decision word is buried in the prose, the corrected call.
		const joined = [decision ?? "", ...paths].join(" ");
		const stem = /not[- ]applicable/i.test(joined)
			? "not-applicable"
			: /updated[- ]first/i.test(joined)
				? "updated-first"
				: /\bchecked\b/i.test(joined)
					? "checked"
					: null;
		fail(
			`unknown docs decision "${decision ?? ""}" — the decision is one word, then its arguments:\n` +
				"  stdd docs updated-first <paths…>\n" +
				"  stdd docs checked <paths…> --reason <why>\n" +
				"  stdd docs not-applicable --reason <why>" +
				(stem ? `\ndid you mean: stdd docs ${stem} …` : ""),
		);
	}
	if (reason !== null) {
		try {
			assertPrintableSingleLine(reason, "docs reason");
		} catch {
			fail("docs reason must be a non-empty single printable line without control characters");
		}
	}
	if (decision === "not-applicable") {
		if (paths.length > 0) {
			fail(
				"not-applicable takes no paths — put the why into --reason:\n" +
					'  stdd docs not-applicable --reason "<why implementation-only>"',
			);
		}
		if (!reason) fail("not-applicable needs --reason <why implementation-only>");
	} else if (paths.length === 0) {
		fail(`${decision} needs at least one docs path`);
	}
	if (decision === "checked" && !reason) {
		fail("checked needs --reason <why no change is needed>");
	}
	for (const docPath of paths) {
		try {
			resolveRepoPath(cwd, docPath, `docs path ${JSON.stringify(docPath)}`);
		} catch (err) {
			fail(err.message);
		}
	}
	const docsContext = ledgerAppendContext(cwd, { event: "docs" });
	const event = {
		event: "docs",
		decision,
		paths,
		snapshot: checkoutSnapshot(cwd),
		...(reason ? { reason } : {}),
		...(docsContext.task ? { taskId: docsContext.task.id } : {}),
	};
	try {
		withCapturedLedgerIdentity(
			cwd,
			{
				expectedBranch: docsContext.branch,
				expectedTaskState: docsContext.taskState,
				subject: "docs evidence",
				retry: "stdd docs",
			},
			() =>
				appendLedger(cwd, event, {
					preserveTaskScope: true,
					lockHeld: true,
					expectedBranch: docsContext.branch,
				}),
		);
	} catch (err) {
		fail(err.message);
	}
	console.log(`stdd docs: recorded ${decision}${paths.length ? ` (${paths.join(", ")})` : ""}`);
}

/**
 * `stdd red|verify -- <cmd>` — run the command, record {cmd, exit, excerpt}
 * verbatim, pass the exit code through. Output flows to the caller unchanged.
 */
function recordRun(cwd, kind, argv) {
	// A single whitespace-carrying word after -- is a description, not a
	// command — it can never spawn. Reject with the corrected form and
	// record nothing: prose in the ledger verifies nothing.
	if (argv.length === 1 && /\s/.test(argv[0])) {
		fail(
			`${kind} takes the command and its arguments, never prose — nothing was recorded\n` +
				`  e.g.:             stdd ${kind} -- pnpm --filter api test\n` +
				`  shell constructs: stdd ${kind} -- sh -c "<cmd>"`,
		);
	}
	// A recorder must know it can persist the result before it launches a
	// command with arbitrary side effects.
	const runContext = ledgerAppendContext(cwd, { event: kind });
	const config = loadConfig(cwd);
	const result = spawnSync(argv[0], argv.slice(1), {
		encoding: "utf8",
		maxBuffer: MAX_SUBPROCESS_BUFFER,
	});
	let exit = result.status ?? 1;
	let output = `${result.stdout ?? ""}${result.stderr ?? ""}`;
	if (result.error) {
		exit = 127;
		output += `${result.error.message}\n`;
	}
	if (result.stdout) process.stdout.write(result.stdout);
	if (result.stderr) process.stderr.write(result.stderr);
	if (result.error) {
		console.error(
			`stdd ${kind}: ${result.error.message}` +
				(result.error.code === "ENOENT"
					? " — command not found; is the worktree ready (stdd doctor --readiness)? " +
						"Shell constructs need sh -c"
					: ""),
		);
	}

	const event = {
		event: kind,
		cmd: argv.join(" "),
		exit,
		excerpt: output.slice(-EXCERPT_LIMIT),
		snapshot: checkoutSnapshot(cwd),
	};
	if (kind === "red") {
		event.genuine = redGenuine(exit, output, config.redPattern ?? null);
		if (exit === 0) {
			console.error('stdd red: the command exited 0 — that is green, not red (recorded genuine: "no")');
		} else if (event.genuine === "unknown") {
			console.error(
				'stdd red: no redPattern in .stdd/config.json — cannot assert genuine-red (recorded genuine: "unknown")',
			);
		} else if (event.genuine === "no") {
			console.error(
				'stdd red: output does not match redPattern — this looks like an environment error, not a genuine red (recorded genuine: "no")',
			);
		}
	}
	try {
		withCapturedLedgerIdentity(
			cwd,
			{
				expectedBranch: runContext.branch,
				expectedTaskState: runContext.taskState,
				subject: `${kind} result`,
				retry: `stdd ${kind}`,
			},
			() =>
				appendLedger(
					cwd,
					{
						...event,
						...(runContext.task ? { taskId: runContext.task.id } : {}),
					},
					{
						preserveTaskScope: true,
						lockHeld: true,
						expectedBranch: runContext.branch,
					},
				),
		);
	} catch (err) {
		fail(err.message);
	}
	process.exit(exit);
}

/**
 * `stdd defer <text>` — record a scope cut under the plan's `## Deferred`
 * section (see method: "The durable plan and stdd defer"). Creates the
 * plan file and the section as needed; never mutates git or appends to the ledger.
 */
function defer(cwd, text) {
	try {
		assertPrintableSingleLine(text, "deferred cut");
	} catch {
		fail("deferred cut must be a non-empty single printable line without control characters");
	}
	// Resolve the mutation target before consulting lifecycle state. This is
	// read-only, but ensures an unsafe plan symlink is diagnosed as the target
	// violation even when the ledger is independently unsafe.
	const planPath = statePath(cwd, PLAN_REL, "plan path");
	const deferContext = ledgerAppendContext(cwd, { event: "defer" });
	if (!deferContext.task) {
		fail('no active task — run `stdd task start "<short name>"` before recording a scope cut');
	}
	const existed = fs.existsSync(planPath);
	let content = "";
	if (existed) {
		const fd = fs.openSync(planPath, "r");
		try {
			content = fs.readFileSync(fd, "utf8");
		} finally {
			fs.closeSync(fd);
		}
	}
	const nextContent = appendDeferred(content, text);
	try {
		withCapturedLedgerIdentity(
			cwd,
			{
				expectedBranch: deferContext.branch,
				expectedTaskState: deferContext.taskState,
				subject: "deferred plan cut",
				retry: "stdd defer",
			},
			() => {
				const stillExists = fs.existsSync(planPath);
				const current = stillExists ? fs.readFileSync(planPath, "utf8") : "";
				if (stillExists !== existed || current !== content) {
					throw new Error(
						"the plan changed before the deferred cut was recorded — nothing recorded; " +
							"rerun `stdd defer` for the current task",
					);
				}
				fs.mkdirSync(path.dirname(planPath), { recursive: true });
				fs.writeFileSync(planPath, nextContent);
			},
		);
	} catch (err) {
		fail(err.message);
	}
	console.log(
		`stdd defer: recorded under ${PLAN_REL} — carry it into the PR description's out-of-scope`,
	);
}

/**
 * Content hashes of every dirty (staged, unstaged, untracked) path.
 * Deleted paths and untracked directories hash to null — equality of
 * nulls still distinguishes inherited state from a slice's own edits.
 */
const DIRTY_FINGERPRINT_READ_LIMIT = 40_000;

function snapshotStatMetadata(st) {
	return [st.dev, st.ino, st.uid, st.gid, st.mode, st.nlink, st.size, st.mtimeNs, st.ctimeNs].join(":");
}

function snapshotOwnerIsCurrent(st) {
	return typeof process.getuid !== "function" || st.uid === BigInt(process.getuid());
}

function sameSnapshotFileObservation(left, right) {
	return sameReviewFileObservation(left, right) && left.uid === right.uid && left.gid === right.gid;
}

function unsafeSnapshotFingerprint(kind, st) {
	return `${kind}:${st ? snapshotStatMetadata(st) : "unstattable"}`;
}

/** Historical raw-byte fingerprint, now read only through a verified fd. */
function fingerprintRawSnapshotDescriptor(descriptor) {
	const hash = createHash("sha256");
	const chunk = Buffer.alloc(64 * 1024);
	let position = 0;
	for (;;) {
		const count = fs.readSync(descriptor, chunk, 0, chunk.length, position);
		if (count === 0) break;
		hash.update(chunk.subarray(0, count));
		position += count;
	}
	return `sha256:${hash.digest("hex")}`;
}

/**
 * Brief-inspection fingerprint for one already-verified descriptor.
 * Oversized files bind a bounded prefix to identity and change metadata;
 * no inspection descriptor reads beyond the inline bound.
 */
function fingerprintBoundedReviewDescriptor(descriptor, opened, retainBytes = false) {
	const oversized = opened.size > BigInt(DIRTY_FINGERPRINT_READ_LIMIT);
	const expected = Number(
		opened.size < BigInt(DIRTY_FINGERPRINT_READ_LIMIT)
			? opened.size
			: BigInt(DIRTY_FINGERPRINT_READ_LIMIT),
	);
	const hash = createHash("sha256");
	if (oversized) {
		hash.update(`stdd-bounded-file-v1:${snapshotStatMetadata(opened)}\n`);
	}
	const retained = retainBytes ? Buffer.alloc(expected) : null;
	const chunk = Buffer.alloc(Math.min(64 * 1024, Math.max(expected, 1)));
	let position = 0;
	while (position < expected) {
		const count = fs.readSync(
			descriptor,
			chunk,
			0,
			Math.min(chunk.length, expected - position),
			position,
		);
		if (count === 0) break;
		hash.update(chunk.subarray(0, count));
		if (retained !== null) chunk.copy(retained, position, 0, count);
		position += count;
	}
	return {
		fingerprint: `sha256:${hash.digest("hex")}`,
		bytes: retained?.subarray(0, position) ?? null,
		complete: position === expected,
		oversized,
	};
}

function fingerprintDirtyPath(abs, observed, boundedReview) {
	if (observed.isSymbolicLink()) {
		try {
			const target = fs.readlinkSync(abs, "buffer");
			const after = fs.lstatSync(abs, { bigint: true });
			if (!after.isSymbolicLink() || !sameSnapshotFileObservation(observed, after)) {
				return unsafeSnapshotFingerprint("unsafe", observed);
			}
			return sha256(`link:${target.toString("latin1")}`);
		} catch {
			return unsafeSnapshotFingerprint("unsafe", observed);
		}
	}
	if (!observed.isFile() || observed.nlink !== 1n || !snapshotOwnerIsCurrent(observed)) {
		return unsafeSnapshotFingerprint("unsafe", observed);
	}

	let descriptor = null;
	try {
		descriptor = fs.openSync(
			abs,
			fs.constants.O_RDONLY | fs.constants.O_NOFOLLOW | fs.constants.O_NONBLOCK,
		);
		const opened = fs.fstatSync(descriptor, { bigint: true });
		const pathAtOpen = fs.lstatSync(abs, { bigint: true });
		if (
			!opened.isFile() ||
			opened.nlink !== 1n ||
			!snapshotOwnerIsCurrent(opened) ||
			pathAtOpen.isSymbolicLink() ||
			!pathAtOpen.isFile() ||
			pathAtOpen.nlink !== 1n ||
			!snapshotOwnerIsCurrent(pathAtOpen) ||
			!sameSnapshotFileObservation(observed, opened) ||
			!sameSnapshotFileObservation(opened, pathAtOpen)
		) {
			return unsafeSnapshotFingerprint("unsafe", observed);
		}
		const fingerprint = boundedReview
			? fingerprintBoundedReviewDescriptor(descriptor, opened)
			: {
					fingerprint: fingerprintRawSnapshotDescriptor(descriptor),
					complete: true,
				};
		const after = fs.fstatSync(descriptor, { bigint: true });
		const finalPath = fs.lstatSync(abs, { bigint: true });
		if (
			!fingerprint.complete ||
			finalPath.isSymbolicLink() ||
			!finalPath.isFile() ||
			finalPath.nlink !== 1n ||
			!snapshotOwnerIsCurrent(after) ||
			!snapshotOwnerIsCurrent(finalPath) ||
			!sameSnapshotFileObservation(opened, after) ||
			!sameSnapshotFileObservation(after, finalPath)
		) {
			return unsafeSnapshotFingerprint("unsafe", observed);
		}
		return fingerprint.fingerprint;
	} catch (err) {
		return unsafeSnapshotFingerprint(err.code === "EACCES" ? "unreadable" : "unsafe", observed);
	} finally {
		if (descriptor !== null) {
			try {
				fs.closeSync(descriptor);
			} catch {
				// The descriptor is no longer part of the snapshot after the verified read.
			}
		}
	}
}

function dirtySnapshot(cwd, { boundedReview = false } = {}) {
	const worker = readWorkerMetadata(cwd);
	if (worker) {
		try {
			return workerDirtySnapshot(worker.root, worker);
		} catch (err) {
			fail(err.message);
		}
	}
	// -z: NUL-delimited, no C-style octal quoting — read as raw bytes so a
	// non-UTF-8 filename is never folded to U+FFFD (which would collapse
	// distinct paths and look up files at the wrong location, letting an
	// untracked doc's content change without staling a review).
	// --untracked-files=all: a wholly untracked directory must list every
	// file inside it, or edits there would never change the snapshot
	const tokens = splitNul(
		execFileSync("git", ["-C", cwd, "status", "--porcelain", "-z", "--untracked-files=all"], {
			stdio: ["ignore", "pipe", "pipe"],
			maxBuffer: MAX_SUBPROCESS_BUFFER,
		}),
	);
	// null-prototype: a file literally named `__proto__` (or `constructor`)
	// must be an own data property, not a write through Object.prototype's
	// setter — otherwise its fingerprint vanishes and edits never stale
	const dirty = Object.create(null);
	for (let i = 0; i < tokens.length; i++) {
		const entry = tokens[i];
		if (entry.length === 0) continue;
		const xy = entry.subarray(0, 2).toString("latin1"); // status bytes are ASCII
		const p = pathForMatch(entry.subarray(3)); // latin1, byte-exact key
		// a rename/copy entry is followed by the origin path token — the
		// current path is what the snapshot tracks
		if (/[RC]/.test(xy)) i++;
		if (isStateExemptPath(cwd, p)) continue;
		// the filesystem path is built from raw bytes, not a decoded string,
		// so a non-UTF-8 name is stat/read at its true location
		const abs = absPathBuf(cwd, p);
		// lstat: a stable symlink is fingerprinted by its target PATH — the
		// change is the link itself. Regular bytes are read only through a
		// no-follow, nonblocking descriptor tied back to this observation.
		let st = null;
		let statError = null;
		try {
			st = p.endsWith("/") ? null : fs.lstatSync(abs, { bigint: true });
		} catch (err) {
			statError = err;
			st = null;
		}
		dirty[p] =
			st === null
				? statError && statError.code !== "ENOENT"
					? unsafeSnapshotFingerprint("unreadable", null)
					: null
				: fingerprintDirtyPath(abs, st, boundedReview);
	}
	return dirty;
}

/**
 * Bind a recorded loop fact to the exact checkout that produced it. HEAD is
 * included deliberately: committing after verification requires a fresh run
 * on the commit that will actually be reviewed and pushed.
 */
function checkoutSnapshot(cwd) {
	let head;
	try {
		head = execFileSync("git", ["-C", cwd, "rev-parse", "HEAD"], {
			encoding: "utf8",
			stdio: ["ignore", "pipe", "pipe"],
		}).trim();
	} catch {
		head = readWorkerMetadata(cwd)?.source.head ?? "(no HEAD)";
	}
	const dirty = dirtySnapshot(cwd);
	return sha256(`${head}\n${JSON.stringify(dirty)}`);
}

const WORKER_METADATA_REL = ".stdd/worker.json";
const WORKER_DELETIONS_REL = ".stdd/worker-deletions";
const WORKER_METADATA_SCHEMA = 1;
const WORKER_EVIDENCE_EVENTS = new Set(["red", "verify", "note"]);
const WORKER_LOCAL_COMMANDS = new Set([
	"red",
	"verify",
	"note",
	"status",
	"scope",
	"doctor",
	"version",
	"--version",
]);

function findWorkerRoot(start) {
	let candidate = path.resolve(start);
	let gitBoundary = null;
	try {
		gitBoundary = path.resolve(
			execFileSync("git", ["-C", candidate, "rev-parse", "--show-toplevel"], {
				encoding: "utf8",
				stdio: ["ignore", "pipe", "pipe"],
			}).trim(),
		);
	} catch {}
	while (true) {
		if (fs.existsSync(path.join(candidate, WORKER_METADATA_REL))) return candidate;
		if (candidate === gitBoundary) return null;
		const parent = path.dirname(candidate);
		if (parent === candidate) return null;
		candidate = parent;
	}
}

function validateWorkerFileState(state) {
	return (
		state === null ||
		(isPlainLedgerRecord(state) &&
			((state.type === "file" &&
				MANIFEST_HASH_PATTERN.test(state.hash) &&
				Number.isInteger(state.mode)) ||
				(state.type === "symlink" &&
					typeof state.target === "string" &&
					MANIFEST_HASH_PATTERN.test(state.hash))))
	);
}

function readWorkerMetadata(cwd, { required = false } = {}) {
	const root = findWorkerRoot(cwd);
	if (!root) {
		if (required) throw new Error("not a managed gitless worker sandbox");
		return null;
	}
	const metadataPath = path.join(root, WORKER_METADATA_REL);
	let parsed;
	let metadataBytes;
	try {
		const observed = fs.lstatSync(metadataPath);
		if (observed.isSymbolicLink() || !observed.isFile() || observed.nlink !== 1) {
			throw new Error("metadata must be a single-linked regular file");
		}
		metadataBytes = fs.readFileSync(metadataPath, "utf8");
		parsed = JSON.parse(metadataBytes);
	} catch (err) {
		throw new Error(`invalid managed worker metadata: ${err.message}`);
	}
	if (
		parsed?.schema !== WORKER_METADATA_SCHEMA ||
		!WORKER_ID_PATTERN.test(parsed.workerId ?? "") ||
		!isPlainLedgerRecord(parsed.source) ||
		!isPrintableSingleLine(parsed.source.root) ||
		!isPrintableSingleLine(parsed.source.branch) ||
		!isPrintableSingleLine(parsed.source.taskId) ||
		!isPrintableSingleLine(parsed.source.taskName) ||
		!isPrintableSingleLine(parsed.source.head) ||
		!isPlainLedgerRecord(parsed.scope) ||
		!isLedgerStringArray(parsed.scope.frozenPaths) ||
		!isLedgerStringArray(parsed.scope.allowedPaths) ||
		parsed.scope.frozenPaths.length + parsed.scope.allowedPaths.length === 0 ||
		!isPlainLedgerRecord(parsed.baseline) ||
		!isPlainLedgerRecord(parsed.baseline.files) ||
		!Object.values(parsed.baseline.files).every(validateWorkerFileState)
	) {
		throw new Error("invalid managed worker metadata schema");
	}
	parsed.baseline.files = Object.assign(Object.create(null), parsed.baseline.files);
	return { ...parsed, root, metadataPath, metadataBytes };
}

const workerPathForMatch = (relative) => Buffer.from(relative, "utf8").toString("latin1");
const workerViewPath = (relative) => viewPath(workerPathForMatch(relative));

function workerIgnoredPaths(root, relativePaths, gitDir) {
	if (relativePaths.length === 0) return new Set();
	try {
		const input = Buffer.concat(relativePaths.map((relative) => Buffer.from(`${relative}\0`)));
		const output = execFileSync(
			"git",
			[`--git-dir=${gitDir}`, `--work-tree=${root}`, "check-ignore", "--no-index", "-z", "--stdin"],
			{ cwd: root, input, stdio: ["pipe", "pipe", "pipe"], maxBuffer: MAX_SUBPROCESS_BUFFER },
		);
		return new Set(splitNul(output).map((entry) => entry.toString("utf8")));
	} catch (err) {
		if (err.status === 1) return new Set();
		throw new Error(`cannot evaluate sandbox ignore rules: ${err.message}`);
	}
}

function workerTreeFiles(root, metadata) {
	const files = new Set();
	const baselinePaths = Object.keys(metadata.baseline.files);
	const baselinePrefixes = new Set();
	for (const baseline of baselinePaths) {
		let prefix = path.posix.dirname(baseline);
		while (prefix !== ".") {
			baselinePrefixes.add(prefix);
			prefix = path.posix.dirname(prefix);
		}
	}
	const gitDir = fs.mkdtempSync(path.join(os.tmpdir(), "stdd-worker-ignore-"));
	const walk = (directory, prefix = "") => {
		const entries = fs.readdirSync(directory, { withFileTypes: true, encoding: "buffer" });
		const names = entries.map((entry) => {
			const name = entry.name.toString("utf8");
			if (!Buffer.from(name, "utf8").equals(entry.name)) {
				throw new Error("managed worker sandbox does not support non-UTF-8 paths");
			}
			return name;
		});
		const relatives = names.map((name) => (prefix ? `${prefix}/${name}` : name));
		const ignored = workerIgnoredPaths(root, relatives, gitDir);
		for (let index = 0; index < entries.length; index++) {
			const entry = entries[index];
			const relative = relatives[index];
			const carriesBaseline =
				Object.hasOwn(metadata.baseline.files, relative) || baselinePrefixes.has(relative);
			if (ignored.has(relative) && !carriesBaseline) continue;
			if (relative.split("/").includes(".git")) {
				throw new Error(`managed worker sandbox must not contain .git: ${workerViewPath(relative)}`);
			}
			if (isStateExemptPath(root, relative) || relative === WORKER_METADATA_REL) continue;
			const absolute = path.join(directory, names[index]);
			if (entry.isDirectory()) walk(absolute, relative);
			else files.add(relative);
		}
	};
	try {
		execFileSync("git", ["init", "--bare", "-q", gitDir], { stdio: "ignore" });
		walk(root);
		return [...files].sort();
	} finally {
		fs.rmSync(gitDir, { recursive: true, force: true });
	}
}

function workerCurrentStates(root, metadata) {
	const paths = new Set([...Object.keys(metadata.baseline.files), ...workerTreeFiles(root, metadata)]);
	const states = Object.create(null);
	for (const relative of paths) states[relative] = readWorkerPathState(root, relative).state;
	return states;
}

function workerDirtySnapshot(root, metadata) {
	const current = workerCurrentStates(root, metadata);
	const dirty = Object.create(null);
	for (const relative of new Set([...Object.keys(metadata.baseline.files), ...Object.keys(current)])) {
		const before = metadata.baseline.files[relative] ?? null;
		const after = current[relative] ?? null;
		if (!sameWorkerState(before, after)) {
			dirty[relative] = after?.hash ?? null;
		}
	}
	return dirty;
}

function validateScopeDeclaration(subject, frozenPaths, allowedPaths) {
	if (frozenPaths.length === 0 && allowedPaths.length === 0) {
		fail(`${subject} needs a scope — pass --frozen <globs> and/or --allowed <globs>`);
	}
	for (const [label, globs] of [
		["--frozen", frozenPaths],
		["--allowed", allowedPaths],
	]) {
		for (const glob of globs) {
			try {
				assertPrintableSingleLine(glob, `${label} glob`);
			} catch {
				fail(
					`${label} glob must be a non-empty single printable line without control or invisible characters`,
				);
			}
		}
	}
}

function workerVisiblePaths(cwd) {
	const output = splitNul(
		execFileSync("git", ["-C", cwd, "ls-files", "--cached", "--others", "--exclude-standard", "-z"], {
			stdio: ["ignore", "pipe", "pipe"],
			maxBuffer: MAX_SUBPROCESS_BUFFER,
		}),
	);
	const paths = [];
	for (const raw of output) {
		if (raw.length === 0) continue;
		const relative = raw.toString("utf8");
		if (!Buffer.from(relative, "utf8").equals(raw)) {
			fail("worker create does not support a non-UTF-8 Git path");
		}
		if (
			relative.split("/").includes(".git") ||
			isStateExemptPath(cwd, relative) ||
			relative === WORKER_METADATA_REL
		) {
			continue;
		}
		try {
			resolveRepoPath(cwd, relative, `worker source path ${JSON.stringify(relative)}`);
		} catch (err) {
			fail(err.message);
		}
		paths.push(relative);
	}
	return [...new Set(paths)].sort();
}

function readWorkerPathState(root, relative, { bytes = false } = {}) {
	resolveRepoPath(root, relative, `worker path ${JSON.stringify(relative)}`);
	const relativeParent = path.posix.dirname(relative);
	const safeParent =
		relativeParent === "."
			? root
			: resolveWritableRepoPath(
					root,
					relativeParent,
					`worker path parent ${JSON.stringify(relativeParent)}`,
				);
	const absolute = path.join(safeParent, path.posix.basename(relative));
	let observed;
	try {
		observed = fs.lstatSync(absolute);
	} catch (err) {
		if (err.code === "ENOENT") return { state: null, bytes: null };
		throw err;
	}
	if (observed.isSymbolicLink()) {
		const target = fs.readlinkSync(absolute);
		const after = fs.lstatSync(absolute);
		if (!after.isSymbolicLink() || !sameFileIdentity(observed, after)) {
			throw new Error(`worker path ${workerViewPath(relative)} changed while reading its symlink`);
		}
		return { state: { type: "symlink", target, hash: sha256(`link:${target}`) }, bytes: null };
	}
	if (!observed.isFile() || observed.nlink !== 1) {
		throw new Error(
			`worker path ${workerViewPath(relative)} must be a single-linked regular file or symlink`,
		);
	}
	const descriptor = fs.openSync(absolute, fs.constants.O_RDONLY | fs.constants.O_NOFOLLOW);
	try {
		const opened = fs.fstatSync(descriptor);
		if (!sameFileIdentity(observed, opened)) {
			throw new Error(`worker path ${workerViewPath(relative)} changed before it could be read`);
		}
		const content = fs.readFileSync(descriptor);
		const after = fs.fstatSync(descriptor);
		const finalPath = fs.lstatSync(absolute);
		if (!sameFileIdentity(opened, after) || !sameFileIdentity(after, finalPath)) {
			throw new Error(`worker path ${workerViewPath(relative)} changed while reading`);
		}
		return {
			state: { type: "file", hash: sha256(content), mode: observed.mode & 0o777 },
			bytes: bytes ? content : null,
		};
	} finally {
		fs.closeSync(descriptor);
	}
}

function writeNewWorkerPath(destination, relative, result) {
	const absolute = resolveWritableRepoPath(
		destination,
		relative,
		`worker destination ${JSON.stringify(relative)}`,
	);
	fs.mkdirSync(path.dirname(absolute), { recursive: true });
	if (result.state === null) return;
	if (result.state.type === "symlink") {
		fs.symlinkSync(result.state.target, absolute);
		return;
	}
	const descriptor = fs.openSync(absolute, "wx", 0o600);
	try {
		fs.writeFileSync(descriptor, result.bytes);
		fs.fchmodSync(descriptor, result.state.mode);
		fs.fsyncSync(descriptor);
	} finally {
		fs.closeSync(descriptor);
	}
	const written = fs.lstatSync(absolute);
	if (!written.isFile() || (written.mode & 0o777) !== result.state.mode) {
		throw new Error(`worker destination mode could not be preserved for ${workerViewPath(relative)}`);
	}
}

function workerCreate(cwd, destinationInput, frozenPaths, allowedPaths) {
	if (process.platform !== "linux") fail("worker create requires Linux held-parent support");
	validateScopeDeclaration("worker create", frozenPaths, allowedPaths);
	const context = ledgerAppendContext(cwd, { event: "worker-create" });
	if (!context.task) fail('worker create needs an active task — run `stdd task start "<name>"`');
	const scoped = scopeLedgerForCheckout(cwd, context.branch);
	const docs = scoped.events.filter((event) => event.event === "docs").at(-1);
	if (!docs) fail("worker create needs a recorded docs decision");
	const destinationLexical = path.resolve(cwd, destinationInput);
	let destinationParent;
	try {
		destinationParent = fs.realpathSync(path.dirname(destinationLexical));
	} catch (err) {
		fail(`worker destination parent is unavailable: ${err.message}`);
	}
	const destination = path.join(destinationParent, path.basename(destinationLexical));
	const source = fs.realpathSync(cwd);
	if (destination === source || destination.startsWith(`${source}${path.sep}`)) {
		fail("worker destination must be outside the source checkout");
	}
	if (fs.existsSync(destination)) fail("worker destination must not exist");
	let enclosingGitRoot = null;
	try {
		enclosingGitRoot = fs.realpathSync(
			execFileSync("git", ["-C", destinationParent, "rev-parse", "--show-toplevel"], {
				encoding: "utf8",
				stdio: ["ignore", "pipe", "pipe"],
			}).trim(),
		);
	} catch {}
	if (
		enclosingGitRoot &&
		(destination === enclosingGitRoot || destination.startsWith(`${enclosingGitRoot}${path.sep}`))
	) {
		fail("worker destination must not be inside any Git checkout");
	}
	const head = execFileSync("git", ["-C", cwd, "rev-parse", "HEAD"], {
		encoding: "utf8",
		stdio: ["ignore", "pipe", "pipe"],
	}).trim();
	const visible = workerVisiblePaths(cwd);
	const tracked = new Set(
		splitNul(
			execFileSync("git", ["-C", cwd, "ls-files", "--cached", "-z"], {
				stdio: ["ignore", "pipe", "pipe"],
			}),
		).map((entry) => entry.toString("utf8")),
	);
	const untracked = visible.filter((relative) => !tracked.has(relative)).length;
	const files = Object.create(null);
	let ownsDestination = false;
	try {
		fs.mkdirSync(destination, { mode: 0o700 });
		ownsDestination = true;
		for (const relative of visible) {
			const result = readWorkerPathState(cwd, relative, { bytes: true });
			files[relative] = result.state;
			writeNewWorkerPath(destination, relative, result);
		}
		const workerId = `worker-${randomBytes(WORKER_ID_RANDOM_BYTES).toString("hex")}`;
		const metadata = {
			schema: WORKER_METADATA_SCHEMA,
			workerId,
			source: {
				root: source,
				branch: context.branch,
				taskId: context.task.id,
				taskName: context.task.name,
				head,
			},
			scope: { frozenPaths, allowedPaths },
			baseline: { files },
		};
		const metadataBytes = `${JSON.stringify(metadata, null, 2)}\n`;
		fs.mkdirSync(path.join(destination, ".stdd"), { recursive: true });
		fs.writeFileSync(path.join(destination, WORKER_METADATA_REL), metadataBytes, {
			flag: "wx",
			mode: 0o600,
		});
		const bootstrap = [
			{
				ts: new Date().toISOString(),
				event: "task-start",
				id: context.task.id,
				name: context.task.name,
				planBaseline: null,
				branch: context.branch,
			},
			{
				...docs,
				ts: new Date().toISOString(),
				branch: context.branch,
				taskId: context.task.id,
			},
			{
				ts: new Date().toISOString(),
				event: "scope",
				frozenPaths,
				allowedPaths,
				baseline: { head, dirty: {} },
				branch: context.branch,
				taskId: context.task.id,
			},
		];
		fs.writeFileSync(
			path.join(destination, ".stdd", "ledger.jsonl"),
			`${bootstrap.map((event) => JSON.stringify(event)).join("\n")}\n`,
			{ flag: "wx", mode: 0o600 },
		);
		withCapturedLedgerIdentity(
			cwd,
			{
				expectedBranch: context.branch,
				expectedTaskState: context.taskState,
				subject: "worker creation",
				retry: "stdd worker create",
			},
			() =>
				appendLedger(
					cwd,
					{
						event: "worker-create",
						workerId,
						metadataHash: sha256(metadataBytes),
						sourceHead: head,
						taskId: context.task.id,
					},
					{
						preserveTaskScope: true,
						lockHeld: true,
						expectedBranch: context.branch,
					},
				),
		);
		console.log(
			`stdd worker: gitless worker ${workerId} created at ${destination} ` +
				`(${visible.length} files, ${untracked} untracked)`,
		);
	} catch (err) {
		fail(
			`${err.message}${ownsDestination ? ` — partial sandbox remains at ${destination}; inspect and remove it explicitly` : ""}`,
		);
	}
}

function sameWorkerState(left, right) {
	if (left === null || left === undefined || right === null || right === undefined) {
		return (left ?? null) === (right ?? null);
	}
	if (left.type !== right.type || left.hash !== right.hash) return false;
	if (left.type === "file") return left.mode === right.mode;
	if (left.type === "symlink") return left.target === right.target;
	return false;
}

function classifyScopePath(frozen, allowed, comparable) {
	if (frozen.some((pattern) => pattern.test(comparable))) return "frozen";
	if (allowed.length > 0 && !allowed.some((pattern) => pattern.test(comparable))) {
		return "outside-allowed";
	}
	return null;
}

function workerScopeViolations(scope, relativePaths) {
	const frozen = scope.frozenPaths.map(latinGlob);
	const allowed = scope.allowedPaths.map(latinGlob);
	return relativePaths.flatMap((relative) => {
		const kind = classifyScopePath(frozen, allowed, workerPathForMatch(relative));
		return kind ? [{ relative, kind }] : [];
	});
}

function openWorkerPublicationParent(cwd, parentRelative) {
	if (parentRelative !== ".") return openOrCreateHeldGeneratedParent(cwd, parentRelative);
	const logicalPath = fs.realpathSync(cwd);
	const before = fs.lstatSync(logicalPath);
	const descriptor = fs.openSync(
		logicalPath,
		fs.constants.O_RDONLY | fs.constants.O_DIRECTORY | fs.constants.O_NOFOLLOW,
	);
	const identity = fs.fstatSync(descriptor);
	if (!sameFileIdentity(before, identity)) {
		fs.closeSync(descriptor);
		throw new Error("source checkout root changed before worker publication");
	}
	return { descriptor, logicalPath, identity, heldPath: `/proc/self/fd/${descriptor}` };
}

function publishWorkerFile(cwd, relative, content, mode) {
	const target = resolveRepoPath(cwd, relative, `worker collection path ${JSON.stringify(relative)}`);
	const parentRelative = path.posix.dirname(relative);
	publishHeldParentFile({
		openDirectory: () => openWorkerPublicationParent(cwd, parentRelative),
		logicalTargetPath: target,
		content,
		mode,
		tempPrefix: ".stdd-worker-collect-",
		identityError: `worker collection path ${JSON.stringify(relative)} changed during publication`,
	});
}

function assertHeldWorkerDirectory(held, label) {
	const descriptorState = fs.fstatSync(held.descriptor);
	const logicalState = fs.lstatSync(held.logicalPath);
	if (
		!sameFileIdentity(held.identity, descriptorState) ||
		!sameFileIdentity(descriptorState, logicalState) ||
		(typeof process.getuid === "function" && descriptorState.uid !== process.getuid())
	) {
		throw new Error(`${label} changed during worker collection`);
	}
}

function publishWorkerSymlink(cwd, relative, target, workerId) {
	const parentRelative = path.posix.dirname(relative);
	const held = openWorkerPublicationParent(cwd, parentRelative);
	const name = path.posix.basename(relative);
	const temp = `.stdd-worker-link-${workerId.slice("worker-".length)}-${randomBytes(8).toString("hex")}`;
	try {
		assertHeldWorkerDirectory(held, `parent of ${workerViewPath(relative)}`);
		fs.symlinkSync(target, path.join(held.heldPath, temp));
		fs.renameSync(path.join(held.heldPath, temp), path.join(held.heldPath, name));
		assertHeldWorkerDirectory(held, `parent of ${workerViewPath(relative)}`);
		const logical = resolveRepoPath(cwd, relative, "collected worker symlink");
		const heldState = fs.lstatSync(path.join(held.heldPath, name));
		const observed = fs.lstatSync(logical);
		if (
			!heldState.isSymbolicLink() ||
			!sameFileIdentity(heldState, observed) ||
			fs.readlinkSync(path.join(held.heldPath, name)) !== target ||
			fs.readlinkSync(logical) !== target
		) {
			throw new Error(`worker collection could not verify ${workerViewPath(relative)}`);
		}
	} finally {
		try {
			fs.unlinkSync(path.join(held.heldPath, temp));
		} catch {}
		fs.closeSync(held.descriptor);
	}
}

function quarantineWorkerDeletion(cwd, relative, workerId, expectedState) {
	const parentRelative = path.posix.dirname(relative);
	const sourceParent = openWorkerPublicationParent(cwd, parentRelative);
	const quarantineRelative = `${WORKER_DELETIONS_REL}/${workerId}`;
	const quarantine = openOrCreateHeldGeneratedParent(cwd, quarantineRelative);
	fs.fchmodSync(quarantine.descriptor, 0o700);
	const sourceName = path.posix.basename(relative);
	const quarantineName = sha256(relative).slice("sha256:".length);
	try {
		assertHeldWorkerDirectory(sourceParent, `source parent of ${workerViewPath(relative)}`);
		assertHeldWorkerDirectory(quarantine, "worker deletion quarantine");
		const liveState = readWorkerPathState(cwd, relative).state;
		const heldSource = fs.lstatSync(path.join(sourceParent.heldPath, sourceName));
		const logicalSource = fs.lstatSync(resolveRepoPath(cwd, relative, "worker deletion source"));
		if (
			!sameWorkerState(liveState, expectedState) ||
			!sameFileIdentity(heldSource, logicalSource) ||
			(typeof process.getuid === "function" && heldSource.uid !== process.getuid())
		) {
			throw new Error(`worker deletion source ${workerViewPath(relative)} changed after preflight`);
		}
		fs.renameSync(
			path.join(sourceParent.heldPath, sourceName),
			path.join(quarantine.heldPath, quarantineName),
		);
		assertHeldWorkerDirectory(sourceParent, `source parent of ${workerViewPath(relative)}`);
		assertHeldWorkerDirectory(quarantine, "worker deletion quarantine");
		const heldQuarantined = fs.lstatSync(path.join(quarantine.heldPath, quarantineName));
		const logicalQuarantined = fs.lstatSync(path.join(quarantine.logicalPath, quarantineName));
		if (
			!sameFileIdentity(heldSource, heldQuarantined) ||
			!sameFileIdentity(heldQuarantined, logicalQuarantined)
		) {
			throw new Error(`worker deletion quarantine could not verify ${workerViewPath(relative)}`);
		}
	} finally {
		fs.closeSync(sourceParent.descriptor);
		fs.closeSync(quarantine.descriptor);
	}
}

function workerCollect(cwd, sandboxInput) {
	if (process.platform !== "linux") fail("worker collect requires Linux held-parent support");
	if (readWorkerMetadata(cwd)) {
		fail("worker collect is source-checkout-owned and unavailable in a managed gitless worker");
	}
	const sandbox = path.resolve(cwd, sandboxInput);
	let metadata;
	try {
		metadata = readWorkerMetadata(sandbox, { required: true });
	} catch (err) {
		fail(err.message);
	}
	const source = fs.realpathSync(cwd);
	if (source !== metadata.source.root) fail("worker collect must run from the bound source checkout");
	const branch = currentBranch(cwd);
	if (branch !== metadata.source.branch) {
		fail(`bound worker branch changed: expected ${metadata.source.branch}, found ${branch ?? "none"}`);
	}
	const collectionContext = ledgerAppendContext(cwd, { event: "note" });
	if (!collectionContext.task || collectionContext.task.id !== metadata.source.taskId) {
		fail("bound worker active task changed or is no longer active");
	}
	const head = execFileSync("git", ["-C", cwd, "rev-parse", "HEAD"], {
		encoding: "utf8",
		stdio: ["ignore", "pipe", "pipe"],
	}).trim();
	if (head !== metadata.source.head) fail("bound worker source HEAD changed");
	const sourceEvents = loadLedger(cwd, branch);
	const binding = sourceEvents
		.filter(
			(event) =>
				event.event === "worker-create" &&
				event.workerId === metadata.workerId &&
				event.taskId === metadata.source.taskId,
		)
		.at(-1);
	if (!binding || binding.metadataHash !== sha256(metadata.metadataBytes)) {
		fail("worker metadata hash does not match its source-ledger binding");
	}

	let current;
	try {
		current = workerCurrentStates(metadata.root, metadata);
	} catch (err) {
		fail(err.message);
	}
	const touched = [];
	for (const relative of new Set([...Object.keys(metadata.baseline.files), ...Object.keys(current)])) {
		const before = metadata.baseline.files[relative] ?? null;
		const after = current[relative] ?? null;
		if (!sameWorkerState(before, after)) touched.push({ relative, before, after });
	}
	const scopeViolation = workerScopeViolations(
		metadata.scope,
		touched.map((change) => change.relative),
	)[0];
	if (scopeViolation) {
		fail(
			`worker scope violation: ${workerViewPath(scopeViolation.relative)} is ` +
				(scopeViolation.kind === "frozen" ? "frozen" : "outside allowed paths"),
		);
	}

	if (touched.some((change) => change.after === null)) {
		try {
			execFileSync(
				"git",
				["-C", cwd, "check-ignore", "--no-index", "-q", `${WORKER_DELETIONS_REL}/probe`],
				{ stdio: "ignore" },
			);
		} catch {
			fail(
				`worker deletion quarantine is not Git-ignored — rerun stdd init before collecting deletions`,
			);
		}
	}

	const prepared = [];
	for (const change of touched) {
		if (
			change.after?.type === "file" &&
			(change.after.mode & 0o022) !== 0 &&
			(change.before?.type !== "file" || change.after.mode !== change.before.mode)
		) {
			fail(`worker path ${workerViewPath(change.relative)} has unsafe group/other write permissions`);
		}
		let sourceState;
		try {
			sourceState = readWorkerPathState(cwd, change.relative).state;
		} catch (err) {
			fail(err.message);
		}
		if (!sameWorkerState(sourceState, change.before) && !sameWorkerState(sourceState, change.after)) {
			fail(
				`worker collect conflict at ${workerViewPath(change.relative)}: source changed since sandbox creation`,
			);
		}
		let finalBytes = null;
		if (change.after?.type === "file") {
			const final = readWorkerPathState(metadata.root, change.relative, { bytes: true });
			if (!sameWorkerState(final.state, change.after)) {
				fail(`worker path ${workerViewPath(change.relative)} changed during collection preflight`);
			}
			finalBytes = final.bytes;
		}
		prepared.push({ ...change, sourceState, finalBytes });
	}

	let workerEvents;
	try {
		const sandboxLedger = rawLedger(metadata.root, metadata.source.branch);
		const invalidIndex = sandboxLedger.findIndex(
			(event) => !isPlainLedgerRecord(event) || !isStateLedgerEvent(event),
		);
		if (invalidIndex !== -1) {
			throw new Error(`invalid event at worker ledger line ${invalidIndex + 1}`);
		}
		workerEvents = sandboxLedger.filter(
			(event) => event.taskId === metadata.source.taskId && WORKER_EVIDENCE_EVENTS.has(event.event),
		);
	} catch (err) {
		fail(`worker evidence is invalid: ${err.message}`);
	}
	const imported = new Set(
		sourceEvents
			.filter(
				(event) => event.workerId === metadata.workerId && typeof event.workerEventHash === "string",
			)
			.map((event) => event.workerEventHash),
	);
	const pendingEvidence = [];
	for (const workerEvent of workerEvents) {
		const workerEventHash = sha256(JSON.stringify(workerEvent));
		if (!imported.has(workerEventHash)) {
			pendingEvidence.push({ workerEvent, workerEventHash });
			imported.add(workerEventHash);
		}
	}

	let applied = 0;
	for (const change of prepared) {
		if (sameWorkerState(change.sourceState, change.after)) continue;
		let liveSource;
		try {
			liveSource = readWorkerPathState(cwd, change.relative).state;
		} catch (err) {
			fail(err.message);
		}
		if (!sameWorkerState(liveSource, change.sourceState)) {
			fail(
				`worker collect conflict at ${workerViewPath(change.relative)}: source changed after preflight`,
			);
		}
		try {
			if (change.after === null) {
				quarantineWorkerDeletion(cwd, change.relative, metadata.workerId, change.sourceState);
			} else if (change.after.type === "symlink") {
				publishWorkerSymlink(cwd, change.relative, change.after.target, metadata.workerId);
			} else {
				publishWorkerFile(cwd, change.relative, change.finalBytes, change.after.mode);
			}
		} catch (err) {
			fail(err.message);
		}
		applied++;
	}

	let evidenceCount = 0;
	if (pendingEvidence.length > 0) {
		try {
			withCapturedLedgerIdentity(
				cwd,
				{
					expectedBranch: collectionContext.branch,
					expectedTaskState: collectionContext.taskState,
					subject: "worker evidence collection",
					retry: "stdd worker collect",
				},
				() => {
					for (const { workerEvent, workerEventHash } of pendingEvidence) {
						const { ts: _ts, branch: _branch, snapshot: _snapshot, ...evidence } = workerEvent;
						appendLedger(
							cwd,
							{
								...evidence,
								taskId: metadata.source.taskId,
								workerId: metadata.workerId,
								workerEventHash,
							},
							{
								preserveTaskScope: true,
								lockHeld: true,
								expectedBranch: collectionContext.branch,
							},
						);
						evidenceCount++;
					}
				},
			);
		} catch (err) {
			fail(err.message);
		}
	}
	console.log(
		`stdd worker: collected ${applied} file change(s) and ${evidenceCount} evidence event(s) ` +
			`from ${metadata.workerId}${applied === 0 && evidenceCount === 0 ? " (already collected)" : ""}`,
	);
}

/**
 * `stdd slice new` — declare a delegated slice's scope and snapshot the
 * checkout baseline (head + dirty-file hashes) into a ledger scope event.
 */
function sliceNew(cwd, frozenPaths, allowedPaths) {
	validateScopeDeclaration("slice new", frozenPaths, allowedPaths);
	const sliceContext = ledgerAppendContext(cwd, { event: "scope" });
	const head = execFileSync("git", ["-C", cwd, "rev-parse", "HEAD"], {
		encoding: "utf8",
		stdio: ["ignore", "pipe", "pipe"],
	}).trim();
	const event = {
		event: "scope",
		frozenPaths,
		allowedPaths,
		baseline: { head, dirty: dirtySnapshot(cwd) },
		...(sliceContext.task ? { taskId: sliceContext.task.id } : {}),
	};
	try {
		withCapturedLedgerIdentity(
			cwd,
			{
				expectedBranch: sliceContext.branch,
				expectedTaskState: sliceContext.taskState,
				subject: "slice scope",
				retry: "stdd slice new",
			},
			() =>
				appendLedger(cwd, event, {
					preserveTaskScope: true,
					lockHeld: true,
					expectedBranch: sliceContext.branch,
				}),
		);
	} catch (err) {
		fail(err.message);
	}
	console.log(
		`stdd slice: scope declared (frozen: ${frozenPaths.join(", ") || "—"}; ` +
			`allowed: ${allowedPaths.join(", ") || "—"}) — baseline at ${head.slice(0, 7)}`,
	);
}

/** Check sandbox-local changes against the scope bound in worker metadata. */
function workerScopeCheck(metadata) {
	let dirty;
	try {
		dirty = workerDirtySnapshot(metadata.root, metadata);
	} catch (err) {
		fail(err.message);
	}
	const violations = workerScopeViolations(metadata.scope, Object.keys(dirty)).map(
		({ relative, kind }) =>
			`${workerViewPath(relative)}: ${kind === "frozen" ? "frozen path modified by this worker" : "outside the allowed paths"}`,
	);
	if (violations.length > 0) {
		console.error(`stdd scope: ${violations.length} violation(s)\n`);
		for (const violation of violations) console.error(`  ${violation}`);
		process.exit(1);
	}
	console.log(`stdd scope: OK (${Object.keys(dirty).length} worker change(s), all in scope)`);
}

/**
 * `stdd scope` — postflight against the slice baseline, not a ref. Only
 * session-introduced changes count; inherited dirt (already modified at
 * baseline, byte-identical now) is reported separately, never blamed.
 */
function scopeCheck(cwd) {
	const worker = readWorkerMetadata(cwd);
	if (worker) return workerScopeCheck(worker);
	const branch = requireBranch(cwd);
	const scope = loadLedger(cwd, branch)
		.filter((e) => e.event === "scope")
		.at(-1);
	if (!scope) {
		fail("no slice declared for this branch — run `stdd slice new --frozen/--allowed` first");
	}
	let committed;
	try {
		// -z + raw bytes: keep committed paths byte-exact so they compare and
		// glob-match consistently with the latin1 keys from dirtySnapshot
		committed = splitNul(
			execFileSync("git", ["-C", cwd, "diff", "--name-only", "-z", scope.baseline.head, "HEAD"], {
				stdio: ["ignore", "pipe", "pipe"],
				maxBuffer: MAX_SUBPROCESS_BUFFER,
			}),
		).map(pathForMatch);
	} catch {
		fail(`baseline commit ${scope.baseline.head.slice(0, 7)} is gone — cannot diff the slice`);
	}
	const introduced = new Set(committed);
	const inherited = [];
	const currentDirty = dirtySnapshot(cwd);
	const baselineDirty = scope.baseline.dirty;
	for (const p of new Set([...Object.keys(baselineDirty), ...Object.keys(currentDirty)])) {
		const baselineHas = Object.hasOwn(baselineDirty, p);
		const currentHas = Object.hasOwn(currentDirty, p);
		if (baselineHas && currentHas && baselineDirty[p] === currentDirty[p]) inherited.push(p);
		else introduced.add(p);
	}
	// stdd's own bookkeeping (the ledger grows during the slice by design;
	// the exact trusted reset temp may exist during recovery) is never in scope.
	// Every other .stdd path is an ordinary deliverable and stays visible.
	for (const p of introduced) {
		if (isStateExemptPath(cwd, p)) introduced.delete(p);
	}
	const frozen = scope.frozenPaths.map(latinGlob);
	const allowed = scope.allowedPaths.map(latinGlob);
	const violations = [];
	for (const p of introduced) {
		const shown = viewPath(p);
		const kind = classifyScopePath(frozen, allowed, p);
		if (kind === "frozen") violations.push(`${shown}: frozen path modified by this slice`);
		else if (kind === "outside-allowed") violations.push(`${shown}: outside the allowed paths`);
	}
	for (const p of inherited) {
		console.log(`inherited dirt (present at baseline, not introduced by this slice): ${viewPath(p)}`);
	}
	if (violations.length > 0) {
		console.error(`stdd scope: ${violations.length} violation(s)\n`);
		for (const v of violations) console.error(`  ${v}`);
		process.exit(1);
	}
	console.log(`stdd scope: OK (${introduced.size} introduced change(s), all in scope)`);
}

